# the physical file must be the final locator that the measured archive will actually encode
def TopMeasPath(TargetValue: KTargetType, Settings: WriteOptions) -> FilePath | None:
    if not isinstance(TargetValue, (str, FilePath)):
        return None
    Requested = FilePath(TargetValue).expanduser().absolute()
    FinalValue = Settings.values.get("final_destination", Requested)
    Failure = "SOLIDWORKS Top box requires its exact measured Windows locator"
    if not isinstance(FinalValue, (str, FilePath)):
        raise ValueError(Failure)
    return MatchMeasPath(Requested, FinalValue, str(FinalValue), Failure)


# measured camera arithmetic and native flags follow the authenticated receipt and exact generated bytes
def EmitTopMeasMut(
    Document: CadDocument,
    TargetValue: KTargetType,
    OptionsValue: WriteOptions | None,
) -> WriteResult:
    WrittenAt, Receipt, Settings = ReadMeasInput(CheckPartOpts(OptionsValue))
    Proof, ProofSha = ReadTopMeas(Receipt)
    OutputPath = TopMeasPath(TargetValue, Settings)
    Prepare = PrepColdTop if IsTopRead(Document) else PrepTopPart
    Candidate = Prepare(
        Document, OutputPath or TargetValue, WrittenAt, Settings, PlatformMath=True
    )
    Evidence = MatchTopMeas(Proof, ProofSha, Candidate)
    Transfers = tuple(
        CapTransfer(Value, TransferMode.KNative)
        for Value in sorted(GetDocumentCaps(Document))
    )
    return PublishMeasMut(
        TargetValue, OutputPath, Settings, Candidate.BytesValue, Evidence, Transfers
    )
