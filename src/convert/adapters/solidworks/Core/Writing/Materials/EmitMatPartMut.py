from convert.adapters.solidworks.Core.Preparation.Materials.PrepMatPart import (
    PrepMatPart,
)
from convert.adapters.solidworks.Core.Writing.Materials.VerifyMatMeas import (
    VerifyMatMeas,
)
from convert.adapters.solidworks.Core.Writing.Measured.CheckMeasPath import (
    CheckMeasPath,
)
from convert.adapters.solidworks.Core.Writing.Measured.PublishMeasMut import (
    PublishMeasMut,
)
from convert.adapters.solidworks.Core.Writing.Measured.ReadMeasInput import (
    ReadMeasInput,
)
from interchange.document.Models.DocumentModel import CadDocument


# both output forms wait for the exact generated physical material archive to match the native evidence
def EmitMatPartMut(
    DocumentValue: CadDocument,
    TargetValue: KTargetType,
    OptionsValue: WriteOptions | None,
) -> WriteResult:
    WrittenAt, Receipt, Settings = ReadMeasInput(OptionsValue)
    OutputPath = (
        FilePath(TargetValue).expanduser().resolve()
        if isinstance(TargetValue, (str, FilePath))
        else None
    )
    if OutputPath is not None:
        CheckMeasPath(OutputPath, Settings)
    Draft = PrepMatPart(DocumentValue, OutputPath or TargetValue, WrittenAt, Settings)
    Evidence = VerifyMatMeas(Receipt, Draft.BytesValue)
    Transfers = tuple(
        CapTransfer(Value, TransferMode.KNative)
        for Value in sorted(GetDocumentCaps(DocumentValue))
    )
    return PublishMeasMut(
        TargetValue, OutputPath, Settings, Draft.BytesValue, Evidence, Transfers
    )
