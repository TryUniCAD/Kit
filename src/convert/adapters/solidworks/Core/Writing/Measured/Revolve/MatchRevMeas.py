from collections.abc import Mapping
from hashlib import sha256 as CalcSha

from convert.adapters.solidworks.Core.Writing.Measured.PartMeasureOpt import (
    KPartMeasureOpt,
)
from convert.adapters.solidworks.Core.Writing.Measured.ReadPartMeas import KOraclePart
from convert.adapters.solidworks.Core.Writing.Measured.Revolve.CheckRevBracket import (
    CheckRevBracket,
)
from convert.adapters.solidworks.Core.Writing.Measured.Revolve.CheckRevLife import (
    CheckRevLife,
)
from convert.adapters.solidworks.Core.Writing.Measured.Revolve.RevReportPins import (
    KRevReports,
)
from convert.adapters.solidworks.Core.Writing.Measured.Revolve.RevEvidence import (
    RevEvidence,
)
from interchange.Core.Common import FreezeMapping


# native flags require the complete regenerated bytes to equal the inspected candidate
def MatchRevMeas(
    Evidence: RevEvidence, Payload: bytes, MeasuredSha: str
) -> Mapping[str, object]:
    Digest = CalcSha(Payload).hexdigest()
    if Digest != MeasuredSha:
        raise ValueError(
            "regenerated SOLIDWORKS revolve has no matching native measurement"
        )
    CheckRevBracket(Evidence)
    Edited, Reopen = CheckRevLife(Evidence, Digest)
    return FreezeMapping(
        {
            KPartMeasureOpt: FreezeMapping(
                {
                    "generated_sha256": Digest,
                    "oracle_build": KOraclePart["build"],
                    "native_result_sha256": KRevReports["native_result"][0],
                    "edit_record_sha256": Edited,
                    "reopen_record_sha256": Reopen,
                }
            )
        }
    )
