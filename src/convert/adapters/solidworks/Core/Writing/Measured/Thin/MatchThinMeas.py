from collections.abc import Mapping
from hashlib import sha256 as CalcSha

from convert.adapters.solidworks.Core.Writing.Measured.PartMeasureOpt import (
    KPartMeasureOpt,
)
from convert.adapters.solidworks.Core.Writing.Measured.ReadMeasMap import ReadMeasMap
from convert.adapters.solidworks.Core.Writing.Measured.ReadMeasRows import ReadMeasRows
from convert.adapters.solidworks.Core.Writing.Measured.ReadMeasSha import ReadMeasSha
from convert.adapters.solidworks.Core.Writing.Measured.MeasOracle import KOraclePart
from interchange.Core.Common import FreezeMapping


# native flags require the complete regenerated bytes to equal the inspected candidate
def MatchThinMeas(
    Payload: bytes, MeasuredSha: str, ReportId: str, CaseValue: dict[str, object]
) -> Mapping[str, object]:
    Digest = CalcSha(Payload).hexdigest()
    if Digest != MeasuredSha:
        raise ValueError(
            "regenerated SOLIDWORKS thin revolve has no matching native measurement"
        )
    PhasesValue = ReadMeasRows(
        ReadMeasMap(CaseValue.get("native_phases")).get("candidate"), 2
    )
    if tuple(RowValue.get("phase") for RowValue in PhasesValue) != (
        "reopen",
        "edited-reopen",
    ) or any(
        RowValue.get("passed") is not True
        or RowValue.get("cold_bodies") != 1
        or RowValue.get("checks_passed") != RowValue.get("checks")
        or ReadMeasMap(RowValue.get("open_status"))
        != {"opened": True, "errors": 0, "warnings": 0}
        for RowValue in PhasesValue
    ):
        raise ValueError("thin revolve does not have a complete native edit and reopen")
    FirstValue, EditValue = PhasesValue
    return FreezeMapping(
        {
            KPartMeasureOpt: FreezeMapping(
                {
                    "generated_sha256": Digest,
                    "oracle_build": KOraclePart["build"],
                    "native_result_sha256": ReportId,
                    "reopen_record_sha256": ReadMeasSha(FirstValue.get("sha256")),
                    "edit_reopen_record_sha256": ReadMeasSha(EditValue.get("sha256")),
                }
            )
        }
    )
