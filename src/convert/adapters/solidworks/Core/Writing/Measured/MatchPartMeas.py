from hashlib import sha256 as CalcSha
from typing import Mapping as TypeMap
from convert.adapters.solidworks.Core.Writing.Measured.CheckMeasSlot import (
    CheckMeasSlot,
)
from convert.adapters.solidworks.Core.Writing.Measured.MatchMeasCase import (
    MatchMeasCase,
)
from convert.adapters.solidworks.Core.Writing.Measured.MeasPhaseMap import MeasPhaseMap
from convert.adapters.solidworks.Core.Writing.Measured.ReadMeasSha import ReadMeasSha
from convert.adapters.solidworks.Core.Writing.Measured.PartMeasureOpt import (
    KPartMeasureOpt,
)
from convert.adapters.solidworks.Core.Writing.Measured.MeasOracle import KOraclePart
from interchange.Core.Common import FreezeMapping


# publication flags only follow the exact full generated bytes and their measured native case
def MatchPartMeas(Receipt: dict[str, object], Payload: bytes) -> TypeMap[str, object]:
    Digest = CalcSha(Payload).hexdigest()
    Label = MatchMeasCase(Receipt, Digest, len(Payload))
    Reports = MeasPhaseMap(Receipt)
    Edited, Reopen = CheckMeasSlot(Reports, Label)
    return FreezeMapping(
        {
            KPartMeasureOpt: FreezeMapping(
                {
                    "generated_sha256": Digest,
                    "oracle_build": KOraclePart["build"],
                    "native_result_sha256": ReadMeasSha(
                        Receipt.get("native_result_sha256")
                    ),
                    "edit_record_sha256": Edited,
                    "reopen_record_sha256": Reopen,
                }
            )
        }
    )
