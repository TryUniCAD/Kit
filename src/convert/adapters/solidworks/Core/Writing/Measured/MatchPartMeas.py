# publication flags only follow the exact full generated bytes and their measured native case
def MatchPartMeas(Receipt: dict[str, object], Payload: bytes) -> TypeMap[str, object]:
    Proof, ProofSha = SnapshotReport(Receipt)
    Digest = CalcSha(Payload).hexdigest()
    Label = MatchMeasCase(Proof, Digest, len(Payload))
    Reports = MeasPhaseMap(Proof)
    Edited, Reopen = CheckMeasSlot(Reports, Label)
    if ProofSha not in KPartReportShas:
        raise ValueError("native measurement requires authenticated standalone part evidence")
    return FreezeMapping(
        {
            KPartMeasureOpt: FreezeMapping(
                {
                    "generated_sha256": Digest,
                    "oracle_build": ReadMeasMap(Proof.get("oracle"))["build"],
                    "native_result_sha256": ReadMeasSha(
                        Proof.get("native_result_sha256")
                    ),
                    "edit_record_sha256": Edited,
                    "reopen_record_sha256": Reopen,
                }
            )
        }
    )
