# a standalone neutral part has no native preferences or save history so its synthesis uses one declared target and a shared writer creation event
def MakePartRecipe(PlanValue: BlindPlan, WrittenAt: int) -> PartBuildInput:
    TargetValue = FeatureTarget(2026306, 370108)
    StyleValue = MakePartStyle()
    CommentValue = "Generated by Kit for SOLIDWORKS 2026 SP05.2"
    TessNumber = 26
    AngularNumber = (TessNumber - 6).bit_length() - 1
    return PartBuildInput(
        StyleValue,
        UnitInput("mm", "degree", "mmgs", 4),
        UnitInput("m", "radian", "mks", 4),
        DefaultPartTree(PlanValue.PlaneName, WrittenAt),
        TargetValue,
        HeaderInput("Kit", "", CommentValue, WrittenAt, WrittenAt, WrittenAt),
        HistoryInput(
            WrittenAt,
            CommentValue,
            TargetValue.DateCode,
            0,
            StyleValue.LanguageId,
            False,
        ),
        ModelDefInput(
            "moISO_c",
            (),
            (TessNumber, AngularNumber, 25, True),
            False,
            "Journal",
            TargetValue.FileVersion,
        ),
        SelfFileInput(
            JoinPath(KNeutralRoot, PlanValue.NameValue + ".SLDPRT"), WrittenAt
        ),
        "ANSI31 (Iron BrickStone)",
        "Configurations",
        1000.0,
        False,
        0,
    )
