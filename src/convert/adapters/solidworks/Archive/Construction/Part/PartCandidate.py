# linked consumers need the actual original constructed model and map identities alongside generated bytes without a decode reconstruction bridge
@DataClass(frozen=True, slots=True)
class PartCandidate:
    SystemValue: PartSystem
    ProfileValue: ProfileGraph
    BossValue: ExtrusionGraph
    HeaderValue: ArchiveNode
    TopHeader: ArchiveNode
    ManagerHeader: ArchiveNode
    DefinitionValue: ModelDefGraph
    ConfigValue: ConfigGraph
    ResolvedValue: ResolvedGraph
    StreamsValue: Mapping[str, bytes]
    BytesValue: bytes
    PlanValue: KPartPlan
    CutValue: CutGraph | None = None
    SelfView: PartSelfView | None = None

    # active configuration access must retain the actual independent manager node rather than invent a part configuration pointer
    @property
    def CurrentConfig(self) -> ArchiveNode:
        return self.SystemValue.ConfigValues[0]
