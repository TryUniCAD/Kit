from convert.adapters.solidworks.Archive.Construction.Files.MakeSelfFile import (
    MakeSelfFile,
)
from convert.adapters.solidworks.Archive.Construction.Header.MakePartHeader import (
    MakePartHeader,
)
from convert.adapters.solidworks.Archive.Construction.Metadata.MakeMgrHeader import (
    MakeMgrHeader,
)
from convert.adapters.solidworks.Archive.Construction.Nodes.PersistentIds import (
    PersistentIds,
)
from convert.adapters.solidworks.Archive.Construction.Part.PartBuildInput import (
    PartBuildInput,
)
from convert.adapters.solidworks.Archive.Construction.System.PartSystem import (
    PartSystem,
)
from convert.adapters.solidworks.Archive.Objects.ArchiveNode import ArchiveNode


# complete part headers must publish the final actual allocator and the same modeled self identity without decoding generated bytes
def MakePartHeaders(
    SystemValue: PartSystem, InputValue: PartBuildInput, Allocator: PersistentIds
) -> tuple[ArchiveNode, ArchiveNode, ArchiveNode]:
    HeaderValue = MakePartHeader(
        SystemValue.RootValue, InputValue.HeaderValue, Allocator, True
    )
    TopHeader = MakePartHeader(
        SystemValue.RootValue, InputValue.HeaderValue, Allocator, False
    )
    SelfValue = MakeSelfFile(
        SystemValue.RootValue,
        HeaderValue,
        SystemValue.ConfigValues[0],
        InputValue.OutputValue,
    )
    HeaderValue.FieldsValue["f38"] = SelfValue
    TopHeader.FieldsValue["f38"] = SelfValue
    return (
        HeaderValue,
        TopHeader,
        MakeMgrHeader(SystemValue.ManagerValue, InputValue.OutputValue.SavedAt),
    )
