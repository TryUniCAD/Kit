from argparse import ArgumentParser
import json
import os
from pathlib import Path, PureWindowsPath
from shutil import copyfileobj
import sys


sys.path.insert(0, str(Path(__file__).resolve().parent))
from PlanarRegistryBuild import (
    CHILD, EPOCH, PARENT, REVISION, SCHEMA, bind, file_sha, load,
    native_parent, require, write,
)


CONTROL = "A22CombinedRotated.SLDASM"
CONTROL_CHILD = "CohortChild.SLDPRT"
CONTROL_HASHES = (
    "fac5708432e569e787dfc00aa87fe08e5ef2d6830ec88f2d69525f8030d9fd1f",
    "b46e1e0f066db55730ce765cb2547b97ad1416e1ea0ceaa588bb8e819f727321",
)
STEPS = ("before", "generated", "reopen", "after")


def exact_file(path, expected):
    require(path.is_file() and not path.is_symlink() and file_sha(path) == expected,
            "a required exact file differs: " + path.name)
    return path


def verify(root, fixture_sha):
    fixture = load(root / "Fixture.json", fixture_sha)
    require(fixture["schema"] == SCHEMA and fixture["revision"] == REVISION
            and fixture["native_acceptance"] is False and fixture["native_processes_started"] == 0
            and fixture["runtime_input_file_reads"] == 0 and fixture["prior_source_inputs_read"] == 0
            and fixture["new_heldout_credit"] == 0,
            "require the independently prepared disclosed default-registry fixture")
    code = root / "CodeRoot"
    manifest = load(root / "CodeManifest.json", fixture["code_manifest_sha256"])
    paths = {path.relative_to(code).as_posix() for path in code.rglob("*.py")}
    require(manifest["revision"] == REVISION and paths == set(manifest["files"]),
            "the exact frozen SDK and observer source closure differs")
    for relative, wanted in manifest["files"].items():
        exact_file(code / relative, wanted)
    bind(code)
    from PortableAsmPrediction import predict
    from RectanglePresentation import differences

    request = load(root / "NeutralRequest.json", fixture["request_sha256"])
    prediction = load(root / "Prediction.json", fixture["prediction_sha256"])
    worker = load(root / "WorkerInput.json", fixture["worker_input_sha256"])
    recomputed = predict(request)
    require(request["saved_at"] == EPOCH and request["native_parent"] == fixture["native_parent"]
            and not differences(prediction, recomputed, absolute=2e-16)
            and worker == {**request, "expected_sha256": {
                name: identity["sha256"] for name, identity in fixture["files"].items()
            }},
            "the default writer request or independent prediction changed")
    require(set(fixture["files"]) == {PARENT, CHILD} and fixture["strict_public_read"]["passed"],
            "the disclosed bundle or strict linked readback is incomplete")
    native = native_parent(fixture["native_parent"])
    for name, identity in fixture["files"].items():
        path = exact_file(root / "FrozenGenerated" / name, identity["sha256"])
        require(path.stat().st_size == identity["bytes"], "a generated byte count changed")
    return fixture, prediction, native, code


def bind_control(root, fixture_sha, control_case, case_sha, control_parent, control_child, packet_windows):
    _, _, native, _ = verify(root, fixture_sha)
    case = load(control_case, case_sha)
    require(case["case"]["name"] == "A22CombinedRotated" and case["case"]["split"] == "discovery"
            and case["child_size_m"] == [.04, .02, .01],
            "the bracket requires the exact disclosed preexisting A22 case")
    paths = tuple(PureWindowsPath(value) for value in (control_parent, control_child))
    require(all(path.is_absolute() and path.name == name
                for path, name in zip(paths, (CONTROL, CONTROL_CHILD), strict=True))
            and paths[0].parent == paths[1].parent and paths[0].parent != native.parent,
            "the A22 original pair must occupy its own actual directory")
    guest = PureWindowsPath(packet_windows)
    require(guest.is_absolute() and guest / "GeneratedInput" / PARENT == native,
            "the packet must own the exact encoded final Windows locator")
    control_sha = write(root / "ControlBinding.json", {
        "schema": SCHEMA, "fixture_sha256": fixture_sha, "source_case_sha256": case_sha,
        "case": case["case"], "child_size_m": case["child_size_m"],
        "paths": [str(path) for path in paths], "file_sha256": list(CONTROL_HASHES),
    })
    path = str(guest / "CodeRoot/re/tooling/sw2026/planar_registry/ObservePlanarRegistry.py")
    args = ["py", "-3.11", "-B", path, "--packet", str(guest),
            "--fixture-sha256", fixture_sha, "--control-sha256", control_sha]
    return write(root / "Recipe.json", {
        "fixture_sha256": fixture_sha, "control_sha256": control_sha,
        "order": list(STEPS), "run_after_even_on_failure": True,
        "argv": {role: [*args, role] for role in (*STEPS, "summary")},
    })


def read_phase(root, role, fixture_sha, control_sha):
    path = root / "Inspection" / role / "Phase.json"
    row = json.loads(path.read_bytes())
    require(row["role"] == role and row["fixture_sha256"] == fixture_sha
            and row["control_sha256"] == control_sha
            and file_sha(path.with_name("Record.json")) == row["native_record"]["record_sha256"],
            "a native lifecycle phase lost its exact receipt binding")
    return row


def controls(root, fixture_sha, control_sha):
    row = load(root / "ControlBinding.json", control_sha)
    require(row["schema"] == SCHEMA and row["fixture_sha256"] == fixture_sha
            and row["file_sha256"] == list(CONTROL_HASHES)
            and row["case"]["name"] == "A22CombinedRotated" and row["child_size_m"] == [.04, .02, .01],
            "control binding differs from the locked disclosed native pair")
    return row, tuple(exact_file(Path(path), digest)
                      for path, digest in zip(row["paths"], CONTROL_HASHES, strict=True))


def postflight(code, source, paths, prediction, saved):
    from interchange.document.Models.DocumentModel import CadDocument
    from ReadSdkOrderedNative import read_process
    from ReadSdkPlanarGroupNative import audit, compare
    from RectanglePresentation import differences, observe

    parent, child = paths
    expected = (saved["parent"], saved["child"]["native_sha256"])
    for path, wanted in zip(paths, expected, strict=True):
        exact_file(path, wanted)
    target = observe(child.read_bytes())
    display_delta = differences(source, target)
    restored = read_process(code, parent)
    read = compare(CadDocument.from_json(restored["document_json"]), prediction, True, file_sha(child))
    linked = {}
    for path, wanted in zip(paths, expected, strict=True):
        record = audit(code, path)
        require(record["passed"] and record["input_sha256"] == wanted,
                "saved linked stream verification read a different artifact")
        exact_file(path, wanted)
        linked[path.name] = record["typed_stream_round_trips"]
    return {
        "saved_child_display": target, "authored_display_discrepancies": display_delta,
        "strict_readback": read, "linked_stream_round_trips": sum(map(len, linked.values())),
        "saved_file_sha256": dict(zip((path.name for path in paths), expected, strict=True)),
        "passed": not display_delta and read["passed"],
    }


def working_copy(root, fixture, paths):
    require(all(not path.exists() and not path.is_symlink() for path in paths),
            "the final native working pair must both be unused")
    paths[0].parent.mkdir()
    for path in paths:
        with (root / "FrozenGenerated" / path.name).open("rb") as incoming, path.open("xb") as output:
            copyfileobj(incoming, output)
        exact_file(path, fixture["files"][path.name]["sha256"])


def phase_run(root, fixture_sha, control_sha, role):
    require(os.name == "nt", "only the designated Windows oracle owner can execute a native phase")
    fixture, prediction, native, code = verify(root, fixture_sha)
    require(Path(__file__).resolve() == code / "re/tooling/sw2026/planar_registry/ObservePlanarRegistry.py",
            "native observation must use the frozen qualified script copy")
    control, original = controls(root, fixture_sha, control_sha)
    from InspectCombinedPlanarMates import phase
    from InspectSdkPlanarGroup import observe_options
    from SdkPlanarGroupPrediction import state_matches

    work = (Path(native), Path(native.with_name(CHILD)))
    require(work[0].parent.name == "GeneratedInput" and work[0].parent.parent.samefile(root),
            "this packet does not own the encoded candidate locators")
    output = root / "Inspection"
    output.mkdir(exist_ok=True)
    target = output / role
    extra = {}
    if role in ("before", "after"):
        job, case, paths = control, control["case"], original
        expected = {"case": case, "assembly_configuration": "Default", "child_configuration": "Default",
                    "child_parameters_m": {"D1@Sketch1": .04, "D2@Sketch1": .02, "D1@Boss-Extrude1": .01},
                    "occurrence_names": [f"CohortChild-{index + 1}" for index in range(len(case["placements"]))]}
    else:
        before = read_phase(root, "before", fixture_sha, control_sha)
        require(before["passed"], "candidate measurement requires its passing independent before control")
        case, paths, expected = prediction["edited_case"], work, prediction
        job = {"case": prediction["case"], "edit_distance_m": prediction["edit_distance_m"],
               "child_size_m": [prediction["child_dimensions_m"][key] for key in ("width", "height", "depth")]}
        if role == "generated":
            require(not target.exists(), "the generated native phase is immutable")
            working_copy(root, fixture, paths)
            extra["editing"] = True
        else:
            first = read_phase(root, "generated", fixture_sha, control_sha)
            require(first["passed"], "fresh reopen requires the generated edit and synchronized saves")
            extra["reopened"] = first["native_record"]["saved"]
    native_row = phase(job, case, role, *paths, target,
                       observe=lambda author, model, child: observe_options(author, model, child, expected),
                       **extra)
    row = {"role": role, "fixture_sha256": fixture_sha, "control_sha256": control_sha,
           "native_record": native_row, "passed": native_row["passed"]}
    try:
        if row["passed"] and role not in ("before", "after"):
            baseline = prediction["initial"] if role == "generated" else prediction["edited"]
            row["analytic_checks"] = {key: state_matches(native_row[key], baseline, prediction)
                                      for key in ("initial", "rebuilt")}
            if role == "generated":
                row["analytic_checks"]["edited"] = state_matches(native_row["edited"], prediction["edited"], prediction)
            row["passed"] &= all(row["analytic_checks"].values())
            if role == "reopen":
                row["saved_postflight"] = postflight(code, fixture["actual_child_display"], work, prediction,
                                                    first["native_record"]["saved"])
                row["passed"] &= row["saved_postflight"]["passed"]
    except Exception as error:
        row["postflight_error"] = repr(error)
        row["passed"] = False
    controls(root, fixture_sha, control_sha)
    write(target / "Phase.json", row)
    return row["passed"]


def summary(root, fixture_sha, control_sha):
    require(os.name == "nt", "the native summary must resolve the untouched controls at their exact Windows paths")
    verify(root, fixture_sha)
    controls(root, fixture_sha, control_sha)
    from InspectCombinedPlanarMates import signature

    phases = {role: read_phase(root, role, fixture_sha, control_sha) for role in STEPS
              if (root / "Inspection" / role / "Phase.json").exists()}
    complete = len(phases) == len(STEPS)
    before, generated, reopen, after = [phases.get(role, {}).get("native_record", {}) for role in STEPS]
    pids = {row.get("oracle_identity", {}).get("process_creation_filetime") for row in (before, generated, reopen, after)} - {None}
    chronological = complete and all(earlier["finished_at"] <= later["started_at"]
                                     for earlier, later in ((before, generated), (generated, reopen), (reopen, after)))
    trees = complete and all(row["passed"] for row in phases.values()) and (
        signature(before["rebuilt"]) == signature(after["rebuilt"])
        and signature(generated["rebuilt"]) == signature(generated["edited"]) == signature(reopen["rebuilt"])
    )
    result = {
        "schema": SCHEMA, "fixture_sha256": fixture_sha, "control_sha256": control_sha,
        "native_process_count": len(pids),
        "controls_healthy": all(phases.get(role, {}).get("passed") is True for role in ("before", "after")),
        "ordered_distinct_lifetimes": chronological and len(pids) == len(STEPS),
        "trees_and_owners_retained": trees,
        "missing_phases": [role for role in STEPS if role not in phases],
        "phase_sha256": {role: file_sha(root / "Inspection" / role / "Phase.json") for role in phases},
        "new_heldout_credit": 0,
    }
    result["passed"] = all(result[key] for key in (
        "controls_healthy", "ordered_distinct_lifetimes", "trees_and_owners_retained",
    ))
    target = root / "Inspection" / "Summary.json"
    digest = write(target, result)
    return {**result, "summary_sha256": digest}


def main():
    parser = ArgumentParser()
    parser.add_argument("mode", choices=("verify", "bind-control", *STEPS, "summary"))
    parser.add_argument("--packet", type=Path, required=True)
    parser.add_argument("--fixture-sha256", required=True)
    parser.add_argument("--control-sha256")
    for option in ("control-case-sha256", "control-parent", "control-child", "windows-packet"):
        parser.add_argument("--" + option)
    parser.add_argument("--control-case", type=Path)
    args = parser.parse_args()
    root = args.packet.resolve()
    if args.mode == "verify":
        verify(root, args.fixture_sha256)
        result = {"passed": True, "native_processes_started": 0}
    elif args.mode == "bind-control":
        require(all(getattr(args, name) is not None for name in (
            "control_case", "control_case_sha256", "control_parent", "control_child", "windows_packet",
        )), "a control binding requires the declared case and both actual native paths")
        digest = bind_control(root, args.fixture_sha256, args.control_case, args.control_case_sha256,
                              args.control_parent, args.control_child, args.windows_packet)
        result = {"passed": True, "recipe_sha256": digest, "native_processes_started": 0}
    else:
        require(args.control_sha256 is not None, "native phases require the exact control binding")
        result = (summary(root, args.fixture_sha256, args.control_sha256) if args.mode == "summary"
                  else {"passed": phase_run(root, args.fixture_sha256, args.control_sha256, args.mode)})
    print(json.dumps(result, sort_keys=True, allow_nan=False))
    raise SystemExit(0 if result["passed"] else 3)


if __name__ == "__main__":
    main()
