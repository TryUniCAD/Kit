import argparse
import codecs
from hashlib import sha256
from importlib import import_module
from io import BytesIO
import json
from pathlib import Path
import sys


def require(condition, message):
    if not condition:
        raise ValueError(message)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--sdk', type=Path, required=True)
    args = parser.parse_args()
    row = json.loads(sys.stdin.read())
    sys.path.insert(0, str(args.sdk / 'src'))
    from convert import open_document
    from convert.adapters.base.WriteOptions import WriteOptions
    from convert.adapters.solidworks.Archive.Objects.ArchiveNode import ArchiveNode
    from convert.adapters.solidworks.Archive.Strings.CStringValue import CStringValue
    from convert.adapters.solidworks.Core.Preparation.Revolve.CanPrepRevolve import CanPrepRevolve
    from convert.adapters.solidworks.Core.Preparation.Revolve.PrepareRevolve import PrepareRevolve
    from convert.adapters.solidworks.Container.Container import SldprtArchive
    from convert.adapters.solidworks.Core.TypedResolved.ReadNativeLink import ReadNativeLink
    from convert.adapters.solidworks.Core.TypedResolved.Revolves.ReadRevOwners import ReadRevOwners
    from interchange.document.Behavior.DocumentIo import FromJson, ToJson
    from interchange.document.Models.DocumentModel import CadDocument
    for encoding in ('ascii', 'utf-8', 'utf-8-sig', 'utf-16-le', 'utf-16-be', 'latin-1'):
        codecs.lookup(encoding)
    for name in ('interchange.document.Models.DocumentProvenance',
        'interchange.document.Validation.DocumentAssemblyValidate',
        'interchange.document.Validation.DocumentFeatureValidate',
        'interchange.document.Validation.DocumentReferenceValidate'):
        import_module(name)
    state = {'enabled': False, 'attempts': []}
    def audit(event, arguments):
        if state['enabled'] and (event == 'open' or event.startswith(('subprocess.', 'socket.'))
            or event in ('os.system', 'os.fork', 'os.posix_spawn', 'ctypes.dlopen')):
            state['attempts'].append(event)
            raise RuntimeError('internal revolve preparation attempted runtime external access')
    sys.addaudithook(audit)
    state['enabled'] = True
    result = {'passed': False, 'heldout_inputs_read': 0, 'native_processes': 0}
    try:
        document = FromJson(CadDocument, row['neutral'])
        epoch = row['spec']['created_at']
        target = row['spec']['self_path']
        options = WriteOptions(configuration=document.configurations[0].id)
        variant = row.get('variant')
        if variant:
            if variant == 'configuration':
                options = WriteOptions(configuration='unavailable configuration')
            elif variant == 'unknown_option':
                options = WriteOptions(values={'unsupported_revolve_switch': True})
            elif variant == 'unnamed_stream':
                target = BytesIO()
            elif variant == 'wrong_suffix':
                target = target[:-7] + '.SLDASM'
            elif variant == 'wrong_basename':
                target = target.replace(row['spec']['name'] + '.SLDPRT', 'UnmodeledRename.SLDPRT')
            elif variant == 'wrong_format':
                options = WriteOptions(destination_format='solidworks.slddrw')
            elif variant == 'bad_epoch':
                epoch = -1
            elif variant == 'wrong_stream_final':
                target = BytesIO()
                options = WriteOptions(values={'final_destination':row['spec']['self_path'].replace('.SLDPRT', '.SLDASM')})
            else:
                raise ValueError('unknown preparation rejection fixture')
            require(not CanPrepRevolve(document, target, epoch, options), 'unsupported preparation was declared supported')
            try:
                PrepareRevolve(document, target, epoch, options)
            except (ValueError, TypeError, KeyError) as error:
                result.update(passed=True, rejected=True, error_class=type(error).__name__, error_message=str(error))
            else:
                raise ValueError('unsupported preparation returned generated bytes')
        else:
            require(CanPrepRevolve(document, target, epoch, options), 'exact ordinary model was not admitted')
            first = PrepareRevolve(document, target, epoch, options)
            stream = BytesIO()
            stream_options = WriteOptions(configuration=document.configurations[0].name,
                values={'final_destination':target})
            require(CanPrepRevolve(document, stream, epoch, stream_options), 'named stream was not admitted')
            second = PrepareRevolve(document, stream, epoch, stream_options)
            require(not stream.getvalue(), 'internal preparation wrote to the caller target')
            require(first.BytesValue == second.BytesValue and sha256(first.BytesValue).hexdigest() == row['sha256'],
                'internal path or stream preparation changed the native qualified bytes')
            require(first.InputValue.OutputValue.PathName == second.InputValue.OutputValue.PathName == target,
                'preparation did not bind the actual final self path')
            self_node = ArchiveNode.RequireNode(first.HeadersValue[0].FieldsValue['f38'])
            require(self_node is first.HeadersValue[1].FieldsValue['f38'], 'both headers lost their actual shared self object')
            handle = ArchiveNode.RequireNode(self_node.FieldsValue['shared']['h18'])
            path_value = handle.FieldsValue['value']
            require(type(path_value) is CStringValue and path_value.TextValue == target, 'serialized self identity differs')
            link = ReadNativeLink(SldprtArchive.from_bytes(first.BytesValue), 0)
            owner, = ReadRevOwners(link)
            require(owner.AngleValue.RadiansValue == first.PlanValue.AngleValue
                and owner.AxisValue.SelectionValue.FieldsValue['ff0']['f00'] == first.ProfileValue.ProfileValue.FieldsValue['f08'],
                'preparation lost the actual angle or selected profile owner')
            public = open_document(first.BytesValue, source_format='solidworks.sldprt',strict=True,
                include_brep=False, include_tessellation=False)
            public.assert_valid()
            require(public.metadata['solidworks.typed_revolve_semantics']['status'] == 'projected', 'normal semantic readback differs')
            result.update(passed=True, rejected=False, sha256=sha256(first.BytesValue).hexdigest(),
                bytes=len(first.BytesValue), named_path_and_stream_equal=True, caller_target_untouched=True,
                actual_header_alias=True, actual_self_path=target, native_profile_id=first.ProfileValue.ProfileValue.FieldsValue['f08'],
                native_feature_id=first.FeatureValue.FieldsValue['f08'], selected_axis_index=owner.AxisValue.IndexValue,
                native_angle_parameter=owner.AngleValue.NameValue)
    finally:
        state['enabled'] = False
    result['runtime_external_attempts'] = state['attempts']
    result['sdk_modules'] = sorted({module.__file__ for name,module in sys.modules.items()
        if (name == 'convert' or name.startswith(('convert.','interchange.'))) and getattr(module,'__file__',None)})
    print(json.dumps(result,allow_nan=False))
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
