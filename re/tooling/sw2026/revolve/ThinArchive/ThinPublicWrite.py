from dataclasses import replace
from importlib import import_module
from io import BytesIO
from pathlib import Path
import sys

from ThinHeldoutPacket import digest, require


FORMAT = "solidworks.sldprt"
POLICY = {"require_native_transfers": True}
NEGATIVES = ("reverse", "rotated-support", "translated-support", "suppressed", "equal-walls",
             "crosses-axis", "double-angular", "foreign-suffix", "unnamed-stream")


def check_result(result, document, payload, path, registry):
    from convert.adapters.base.TransferContract import TransferMode

    require((result.path, result.adapter, result.bytes_written) == (path, FORMAT, len(payload))
            and result.vendor_loadable and result.application_usable and not result.dropped
            and not result.carrier_capabilities and not result.requirements, "native-only publication receipt differs")
    if registry:
        require(document.capabilities <= result.native_capabilities
                and all(row.mode is TransferMode.KNative for row in result.transfers),
                "registered thin writer omitted a declared native transfer")


def write_candidate(request):
    from BuildThinPlanes import measure_plane, portable
    from VerifySdkCircleEndRegistration import OutputGuard
    from convert import write_document
    from convert.adapters.base.WriteOptions import WriteOptions
    from convert.adapters.solidworks.Core.Preparation.Revolve.PrepareRevolve import PrepareRevolve
    from convert.api.ApiContext import GetRegistry

    root, case = Path(request["scratch"]).resolve(), request["case"]
    locator, epoch = request["locator"], request["epoch"]
    filename = case["name"] + ".SLDPRT"
    normal = root / "Published" / filename
    direct = root / "Direct" / filename
    direct.parent.mkdir()
    writer = GetRegistry().GetWriter(FORMAT)
    emitter = import_module("convert.adapters.solidworks.Core.Writing.EmitNativeMut")
    emitter.ReadTime = lambda: epoch
    guard = OutputGuard(root, filename)
    sys.addaudithook(guard.audit)
    original_policy = {**POLICY, "final_destination": locator}
    fresh_policy = {**POLICY, "final_destination": str(normal)}

    def buffer_receipts(payload, policy):
        for use_registry in (False, True):
            target = BytesIO()
            result = (write_document(document, target, destination_format=FORMAT, allow_carrier=False, values=policy)
                      if use_registry else writer.write(document, target, WriteOptions(values=policy)))
            require(target.getvalue() == payload, "direct or registry stream did not reproduce exact generated bytes")
            check_result(result, document, payload, None, use_registry)

    with guard.active("memory"):
        document = portable(case)
        require(writer.supports(document, normal), "direct adapter did not acquire the witnessed thin part")
        original = PrepareRevolve(document, locator, epoch).BytesValue
        require(digest(original) == request["candidate_sha256"], "native measured original locator bytes differ")
        slot = BytesIO()
        require(PrepareRevolve(document, slot, epoch, WriteOptions(values=original_policy)).BytesValue == original
                and not slot.getvalue(), "logical preparation path and named stream differ")
        buffer_receipts(original, original_policy)
        fresh = PrepareRevolve(document, normal, epoch).BytesValue
        buffer_receipts(fresh, fresh_policy)
        original_frames = measure_plane(original, case)
        fresh_frames = measure_plane(fresh, case)
        require(len(original_frames["typed_streams"]) == len(fresh_frames["typed_streams"]) == 10,
                "thin publication lost its exact linked stream owners")
    with guard.active("path"):
        file_result = writer.write(document, direct, WriteOptions(values=fresh_policy))
        path_result = write_document(document, normal, allow_carrier=False, values=POLICY)
        check_result(file_result, document, fresh, direct, False)
        check_result(path_result, document, fresh, normal, True)
    require(normal.read_bytes() == direct.read_bytes() == fresh and tuple(normal.parent.iterdir()) == (normal,),
            "named and staged public paths diverged or left an intermediate artifact")
    return {"original_locator_sha256": digest(original), "fresh_locator_sha256": digest(fresh),
            "exact_streams": 10, "original_locator_stream_routes": 2, "fresh_locator_public_routes": 4,
            "native_capabilities": sorted(value.value for value in path_result.native_capabilities),
            "runtime_input_file_reads": len(guard.denied)}, original, fresh


def synthetic(negative):
    from BuildThinPlanes import portable
    from interchange.geometry.Models.VectorSpace import SpaceVector

    case = {"name": "ThinScopeRefusal", "plane": "top", "reverse": negative == "reverse", "axis_x_m": 0.003,
            "profile_radius_m": 0.022, "axis_axial_m": [-.045, .065], "axial_m": [-.014, .032],
            "angle_deg": 66.0, "edit_angle_deg": 91.0, "wall_m": [0.0014, 0.0026],
            "wall_mode": "two", "edit_wall_m": [0.0019, 0.0031], "first_wall_sign": 1,
            "family": "thin", "split": "discovery"}
    if negative == "equal-walls":
        case["wall_m"][1] = case["wall_m"][0]
    if negative == "crosses-axis":
        case["wall_m"][1] = 0.024
    document = portable(case)
    if negative in ("rotated-support", "translated-support"):
        (plane,) = document.support_planes
        frame = (replace(plane.transform, x_axis=SpaceVector(-1, 0, 0), y_axis=SpaceVector(0, 0, 1))
                 if negative == "rotated-support" else replace(plane.transform, origin=SpaceVector(1, 0, 0)))
        document = replace(document, support_planes=(replace(plane, transform=frame),))
    if negative == "suppressed":
        (sketch,) = document.sketches
        document = replace(document, sketches=(replace(sketch, suppressed=True),))
    if negative == "double-angular":
        (feature,) = document.feature_timeline
        sweep = replace(feature.definition.SweepValue, SideMode="symmetric_full")
        document = replace(document, feature_timeline=(replace(feature, definition=replace(feature.definition, SweepValue=sweep)),))
    return document


def rejection(request):
    from VerifySdkCircleEndRegistration import OutputGuard
    from convert import write_document
    from convert.adapters.base.WriteOptions import WriteOptions
    from convert.adapters.registry import AdapterNotFoundError
    from convert.api.ApiContext import GetRegistry

    name, root = request["negative"], Path(request["scratch"]).resolve()
    suffix = ".SLDASM" if name == "foreign-suffix" else ".SLDPRT"
    path = root / "Refused" / ("ThinScopeRefusal" + suffix)
    guard = OutputGuard(root, path.name)
    writer = GetRegistry().GetWriter(FORMAT)
    document = synthetic(name)
    document.assert_valid()
    sys.addaudithook(guard.audit)
    prior = b"previous sink data"
    opts = {} if name == "unnamed-stream" else {"final_destination": str(path)}
    targets = [BytesIO(prior)] if name == "unnamed-stream" else [path, BytesIO(prior)]
    for direct in (False, True):
        for target in targets:
            with guard.active("memory"):
                try:
                    if direct:
                        writer.write(document, target, WriteOptions(values=opts))
                    else:
                        write_document(document, target, destination_format=FORMAT, allow_carrier=False, values=opts)
                except (ValueError, TypeError, AdapterNotFoundError):
                    pass
                else:
                    raise ValueError("unqualified thin input reached native output")
            if isinstance(target, BytesIO):
                require(target.getvalue() == prior and target.tell() == 0, "public refusal altered an existing stream")
    require(not path.exists() and not path.parent.exists(), "public thin refusal left a staging artifact")
    return {"negative": name, "mirrored_refusal": True, "runtime_input_file_reads": len(guard.denied)}
