def read_json(path, sha, owner):
    return json.loads(baseline.checked(path, sha, owner=owner).read_bytes())


def read_features(path, rules, version):
    from defs.ConfigPart import load_config, store_config_state
    from defs.ResolvedCore import load_resolved, store_resolved_state
    from convert.adapters.solidworks.Container.Container import SldprtArchive

    archive = SldprtArchive.from_bytes(path.read_bytes())
    config_data, resolved_data = (archive.require(stream) for stream in (CONFIG, RESOLVED))
    config, config_map = load_config(config_data, rules, version, archive=archive, name=CONFIG)
    seed = config_map.map_state()
    resolved, resolved_map = load_resolved(resolved_data, rules, version, archive=archive, name=RESOLVED, seed=seed)
    require(not config.tail and store_config_state(config, rules, version)[0] == config_data
            and not resolved.tail and store_resolved_state(resolved, rules, version, seed=seed)[0] == resolved_data,
            "linked Config-0 and ResolvedFeatures must round trip exactly")
    root, = config.roots
    return archive, root, resolved.roots, resolved_map.map_state()


def positive_value(display):
    handle, = display["f850"]
    value = handle["o"]["ff0"]
    parameter = value["f28"]
    require(parameter.cls == "moLengthParameter_c" and parameter["f18"]["f08"] == "D1", "typed owner lacks its authored length D1")
    metres = parameter["f58"]
    require(baseline.finite(metres) and metres > 0, "typed length D1 is not positive and finite")
    return metres


def child_scope(path, expected_depth):
    from Classes import registry
    from Core import DOCUMENT_VERSION_2026

    _, _, features, _ = read_features(path, registry(), DOCUMENT_VERSION_2026)
    sketch, = (node for node in features if node.cls == "moProfileFeature_c")
    boss, = (node for node in features if node.cls == "moExtrusion_c")
    require(sketch["f18"]["f08"] == "Sketch1" and boss["f18"]["f08"] == "Boss-Extrude1"
            and any(row["o"] is sketch for row in boss["f60"]["list"]["items"]), "typed child lost its extrusion profile")
    dimensions = sketch["pd_f80"]["dims"]
    counts = {name: len(dimensions[name]) for name in SKETCH_DIMENSION_ROLES}
    display_count = len(dimensions["f118"]["items"])
    require(not any(counts.values()) and display_count == 0 and positive_value(boss["f818"]["f18"]) == expected_depth,
            "typed child differs from the vertex-authored sketch and active boss depth")
    return {
        "sketch_dimension_record_counts": counts, "sketch_display_dimension_count": display_count,
        "expected_native_parameters_m": dict(zip(baseline.DIMENSIONS, (None, None, expected_depth), strict=True)),
    }


def source_identity(source):
    original = read_json(source / "Trial.json", edit.SOURCE_TRIAL, source)
    plan = read_json(source / "EncodedPaths.json", SOURCE_PATH_PLAN, source)
    report = read_json(source / "Inspection/DistanceMateResults.json", edit.REPLAY_RESULT, source)
    require(report["path_plan_sha256"] == SOURCE_PATH_PLAN and report["controls_healthy"] and report["staged_inputs_unchanged"]
            and not report["passed"] and plan["generated_files"] == original["generated"]["files"], "prior exact-path measurement differs")
    return original, plan


def regenerated_request(source, candidate, original, writer):
    prior = read_json(source / "Request.json", original["source_artifact_sha256"]["Request.json"], source)
    request = read_json(candidate / "Request.json", writer["request_sha256"], candidate)
    report = read_json(candidate / "GeneratorReport.json", writer["generator_report_sha256"], candidate)
    require(report["schema"] == "kit.sw2026.generated-distance-mate-bundle.v1" and report["split"] == "discovery"
            and report["input_runtime_file_access_attempts"] == report["heldout_inputs_tested"] == 0 and report["native_acceptance"] is False
            and report["writer_output_count"] == 2, "regenerated bundle must be generated by the guarded discovery process")
    old_report = read_json(source / "GeneratorReport.json", original["source_artifact_sha256"]["GeneratorReport.json"], source)
    require(report["inspection"] == old_report["inspection"], "relocating the authored paths changed the distance graph inspection")
    roles = (("assembly", original["case"]["name"] + ".SLDASM"), ("child", original["case"]["child"]))
    encoded, files = {}, {}
    for role, name in roles:
        expected = str(edit.ENCODED_PARENT / name)
        require(request["bundle"][role]["output"]["path_name"] == expected, "the regenerated request does not target its new exact directory")
        prior["bundle"][role]["output"]["path_name"] = expected
        encoded[name] = expected
        asset = report[role]
        require(set(asset) == {"bytes", "sha256", "streams"}, "the staged generator report must exclude native byte payloads")
        files[name] = {key: asset[key] for key in ("bytes", "sha256")}
        require(files[name]["sha256"] != original["files"][name]["sha256"], "new encoded destinations must be independently generated")
    require(prior == request and "rectangle_dimensions" not in request["bundle"]["child"]["document"],
            "the regenerated neutral model changed beyond the two output paths")
    require(files == writer["generated_files"], "the regenerated file manifest differs from the writer receipt")
    return request, encoded, files


def prepare(source, candidate, evidence, output):
    require(source.parent == output.parent and not output.exists() and not output.is_symlink()
            and all(folder != output for folder in (source, candidate)), "choose an unused private output beside the disclosed replay")
    original, previous_plan = source_identity(source)
    old = original["generated"]
    writer = json.loads((candidate / "WriterReceipt.json").read_bytes())
    source_map = read_json(candidate / "WriterSource.json", writer["pinned_python_source_manifest_sha256"], candidate)
    require(writer["writer_revision"] == old["writer_revision"] and writer["writer_tool_hashes"] == old["writer_tool_hashes"]
            and len(source_map) == writer["pinned_python_file_count"]
            and all(source_map["re/tooling/sw2026/" + name] == sha for name, sha in writer["writer_tool_hashes"].items()),
            "regenerated writer source does not match the frozen commit")
    request, encoded, files = regenerated_request(source, candidate, old, writer)
    require(digest(evidence) == edit.REPLAY_EVIDENCE, "wrong sanitized read-only evidence")
    paths = baseline.pair_paths(candidate, old["case"], files)
    observed = read_encoded_paths(paths)
    parent, child = (encoded[path.name] for path in paths)
    require(all(row == {"self": parent, "children": [child]} for row in observed["parent_headers"].values())
            and all(row == {"self": child, "children": []} for row in observed["child_headers"].values())
            and observed["occurrence_refs"] == [{"name": name, "child": child, "parent_backlink": parent} for name in old["case"]["occurrence_names"]],
            "typed regenerated paths differ from the authored output paths")
    scope = child_scope(paths[1], request["bundle"]["child"]["document"]["depth_m"])
    output.mkdir()
    tools, frozen = output / "Tools", output / "FrozenGenerated"
    tools.mkdir()
    frozen.mkdir()
    tool_hashes = original["tool_hashes"] | {"InspectEncodedDistanceMate.py": previous_plan["observer_sha256"]}
    for name, sha in tool_hashes.items():
        copyfile(baseline.checked(source / "Tools" / name, sha, owner=source / "Tools"), tools / name)
    copyfile(edit.SCRIPT, tools / edit.SCRIPT.name)
    copyfile(evidence, output / "PriorNativeOpen.json")
    for name in edit.ARTIFACTS[:-1]:
        copyfile(candidate / name, output / name)
    for path in paths:
        copyfile(path, frozen / path.name)
    packet = output / "EditTrial.json"
    write_json(packet, {
        "schema": edit.SCHEMA, "native_acceptance": False, "heldout_inputs_tested": 0,
        "source_trial_sha256": edit.SOURCE_TRIAL, "oracle_sha256": original["oracle_sha256"], "oracle_file_version": original["oracle_file_version"],
        "preparer_sha256": digest(__file__), "tool_hashes": tool_hashes | {edit.SCRIPT.name: digest(edit.SCRIPT)},
        "artifact_sha256": {name: digest(output / name) for name in edit.ARTIFACTS}, "control": original["control"],
        "generated": {
            "case": old["case"], "files": files, "writer_revision": writer["writer_revision"], "writer_tool_hashes": writer["writer_tool_hashes"],
            "encoded_paths_by_file": encoded, "expected_tree": old["expected_tree"], "child_parameters_m": scope["expected_native_parameters_m"],
            "typed_child": scope, "typed_paths": observed,
        },
    })
    sha = digest(packet)
    subprocess.run([sys.executable, "-B", str(tools / edit.SCRIPT.name), "verify", str(packet), "--packet-sha256", sha],
                   check=True, capture_output=True, timeout=25)
    return {"packet": str(packet), "packet_sha256": sha, "observer_sha256": digest(edit.SCRIPT), "preparer_sha256": digest(__file__)}


def saved_distance(parent, child, case):
    from AssemblyMates import load_mate_list, store_mate_list
    from Classes import registry
    from Core import DOCUMENT_VERSION_2026 as version

    rules = registry()
    archive, assembly, _, seed = read_features(parent, rules, version)
    _, _, child_features, _ = read_features(child, rules, version)
    datum, = (node for node in child_features if node.cls == "moRefPlane_c" and node["f18"]["f08"] == baseline.PLANE)
    components = {row["o"]["f18"]["f08"]: row["o"] for row in assembly["f68"]["list"]["items"]}
    require(set(components) == set(case["occurrence_names"]), "saved assembly has different occurrence identities")
    payload = archive.require(MATES)
    (mate,), load = load_mate_list(payload, rules, version, resolved_map=seed)
    require(not load.left() and store_mate_list((mate,), rules, version, resolved_map=seed) == payload, "native-saved mate list did not round trip")
    require(mate.cls == "moMateDistanceDim_c" and mate["f18"]["f08"] == baseline.MATE and mate["f3b4"] == 1,
            "native-saved mate lost its aligned distance class")
    metres = positive_value(mate["f4b8"])
    require(baseline.close(metres, case["planned_distance_edit_m"], relative=0, absolute=1e-12), "native-saved D1 does not retain the edit")
    participants = []
    require(len(mate["f410"]) == 2, "native-saved mate does not retain two concrete plane wrappers")
    for index, (name, item) in enumerate(zip(case["occurrence_names"], mate["f410"], strict=True)):
        occurrence = components[name]
        wrapper = item["o"]
        plane = wrapper["f58"]
        chain = plane["f58"]
        backlink, = (row["o"] for row in chain["f20"]["f08"]["f08"])
        require(wrapper.cls == "moPlaneRef_w" and plane.cls == "moCompRefPlane_c" and chain.cls == "moChainComponent_c"
                and chain["owner"] is assembly and backlink is occurrence["f4f8"] and backlink["f50"] is occurrence
                and plane["ff0"]["f00"] == datum["f08"] and [wrapper[key] for key in ("f74", "f78", "f7c")] == [mate["f08"], index, index],
                "native-saved mate lost ordered Right Plane object ownership")
        participants.append({"occurrence": name, "occurrence_id": occurrence["f08"], "datum_id": datum["f08"], "plane": baseline.PLANE})
    first, second = (components[name] for name in case["occurrence_names"])
    require([first["f408"], second["f408"]] == [1, 0], "native-saved assembly lost the fixed anchor")
    expected = case["placements"][1]["translation_m"][1:]
    translation = [second["f360"][key] for key in ("f58", "f60", "f68")]
    require(all(baseline.close(value, target, relative=0, absolute=1e-10)
                for value, target in zip(translation, (metres, *expected), strict=True)), "native-saved moving placement differs from the edited intent")
    return {"name": baseline.MATE, "driving_dimension_m": metres, "ordered_endpoints": participants, "moving_translation_m": translation,
            "linked_stream_bytes_and_mate_bytes_round_trip": True}


def check_saved(packet_path, packet_sha, result_sha, output):
    root = packet_path.parent
    packet = read_json(packet_path, packet_sha, root)
    result = read_json(root / "Inspection/DistanceMateEditResults.json", result_sha, root)
    require(packet["schema"] == result["schema"] == edit.SCHEMA and result["packet_sha256"] == packet_sha
            and result["passed"] and result["controls_healthy"] and result["distinct_processes"] == 4
            and result["native_persistence_passed"] and result["driving_edit_passed"] and result["frozen_inputs_unchanged"]
            and result["heldout_inputs_tested"] == 0, "native result did not qualify the owned edit and fresh reopen")
    _, made, reopened, _ = result["phases"]
    require((made["label"], reopened["label"]) == ("GeneratedEdit", "GeneratedReopen") and made["save"]["passed"],
            "owned file save receipt is incomplete")
    case = packet["generated"]["case"]
    paths = baseline.pair_paths(root / "SavedBundle", case, made["save"]["files"])
    semantics = saved_distance(*paths, case)
    receipt = {
        "schema": "kit.sw2026.saved-distance-mate-readback.v1", "packet_sha256": packet_sha, "native_result_sha256": result_sha,
        "files": made["save"]["files"], "typed_mate": semantics, "heldout_inputs_tested": 0,
    }
    with output.open("x", encoding="utf-8") as stream:
        stream.write(json.dumps(receipt, indent=2, allow_nan=False) + "\n")
    return {"receipt": str(output), "receipt_sha256": digest(output)}


def main():
    parser = argparse.ArgumentParser(description="Freeze the independent native distance edit or read back its hash-bound saved bundle")
    subcommands = parser.add_subparsers(dest="mode", required=True)
    prep = subcommands.add_parser("prepare")
    for name in ("encoded_readonly_trial", "regenerated_pair", "sanitized_native_evidence", "output"):
        prep.add_argument(name, type=Path)
    saved = subcommands.add_parser("check-saved")
    saved.add_argument("packet", type=Path)
    saved.add_argument("output", type=Path)
    saved.add_argument("--packet-sha256", required=True)
    saved.add_argument("--native-result-sha256", required=True)
    args = parser.parse_args()
    if args.mode == "prepare":
        result = prepare(args.encoded_readonly_trial.resolve(strict=True), args.regenerated_pair.resolve(strict=True),
                         args.sanitized_native_evidence.resolve(strict=True), args.output.absolute())
    else:
        result = check_saved(args.packet.resolve(strict=True), args.packet_sha256, args.native_result_sha256, args.output.absolute())
    print(json.dumps(result, sort_keys=True))


if __name__ == "__main__":
    main()
