SCHEMA = "kit.sw2026.sdk-corner-native.v1"
TOOLS = {"AuthorCurves.py", "AuthorRectangleAnchors.py", "InspectFresh.py", "InspectSdkBlindPart.py",
         "InspectSdkCorner.py", "SdkCornerNativeGraph.py", "OracleIdentity.py", "Swapp.py"}


def checked(root, name, expected):
    path = (root / name).resolve(strict=True)
    curves.require(path.parent == root and path.is_file() and curves.digest(path) == expected,
                   "frozen corner evidence differs: " + name)
    return path


def verify(packet, expected):
    root = packet.parent.resolve(strict=True)
    job = json.loads(checked(root, packet.name, expected).read_bytes())
    curves.require(job["schema"] == SCHEMA and job["oracle_sha256"] == ORACLE and
                   job["control_sha256"] == CONTROL and job["heldout_inputs_read"] == 0 and
                   job["fcstd_conversion_accepted"] is False, "expected a source-only synthetic corner discovery packet")
    tools = root / "Tools"
    curves.require(Path(__file__).resolve().parent == tools and set(job["tools_sha256"]) == TOOLS,
                   "use the complete frozen native corner observer")
    for name, digest in job["tools_sha256"].items():
        checked(tools, name, digest)
    curves.require(set(job["inputs_sha256"]) == {"Control.SLDPRT", "Candidate.SLDPRT", "Case.json", "Request.json", "Build.json",
                   "Repeat.json", "Prepare.json", "Counterpart.json", "WriterManifest.json", "FrozenSource.json"},
                   "native corner input manifest differs")
    for name, digest in job["inputs_sha256"].items():
        checked(root, name, digest)
    curves.require(job["inputs_sha256"]["Control.SLDPRT"] == CONTROL, "pristine native control differs")
    request, build, repeat, prepared, compared, case, writer, closure = (
        json.loads((root / name).read_bytes()) for name in
        ("Request.json", "Build.json", "Repeat.json", "Prepare.json", "Counterpart.json", "Case.json", "WriterManifest.json", "FrozenSource.json"))
    candidate = root / "Candidate.SLDPRT"
    curves.require(build == repeat and build["sha256"] == job["inputs_sha256"]["Candidate.SLDPRT"] and
                   b64decode(build["blob"], validate=True) == candidate.read_bytes() and build["bytes"] == candidate.stat().st_size,
                   "native corner requires exact repeated guarded generated bytes")
    curves.require(all(report["passed"] and report["runtime_input_file_reads"] == 0 and report["native_acceptance"] is False and
                   report["public_writer_qualified"] is False for report in (build, prepared, compared)) and
                   build["sdk_runtime_research_imports"] == prepared["sdk_runtime_research_imports"] == 0,
                   "native corner source-only proof is incomplete")
    curves.require(len(build["streams"]) == len(compared["streams"]) == 10 and
                   all(row["same_as_independent_research"] and row["sha256"] == build["streams"][name]["sha256"]
                       for name, row in compared["streams"].items()) and all(prepared["byte_identity"].values()),
                   "native corner needs independent stream and typed graph identity")
    curves.require(writer["file_count"] == len(writer["files"]) and all(
                   closure["files_sha256"][row["path"]] == row["sha256"] for row in writer["files"]),
                   "native corner writer manifest does not bind the exact source closure")
    document = request["document"]
    sketch = document["sketches"]["$tuple"][0]
    feature = document["feature_timeline"]["$tuple"][0]
    curves.require(case["model_name"] == build["name"] and case["self_path"] == build["native_path"] and
                   case["profile"] == sketch["name"] and case["feature"] == feature["name"] and
                   case["origin"] == request["settings"]["system"]["origin_name"] and
                   case["support"] == document["support_planes"]["$tuple"][0]["name"] and
                   case["configuration_name"] == document["configurations"]["$tuple"][0]["name"] and
                   case["density_kg_m3"] == request["settings"]["density_kg_m3"] and
                   case["vertices_m"] == build["vertices_m"] and case["depth_m"] == build["depth_m"],
                   "native corner expectations differ from the actual explicit neutral request")
    names = ["D1@" + case["profile"], "D2@" + case["profile"], "D1@" + case["feature"]]
    lengths = [case["vertices_m"][1][0], case["vertices_m"][2][1], case["depth_m"]]
    curves.require(case["parameter_names"] == names and set(case["dimensions_m"]) == set(names) and
                   [case["dimensions_m"][name] for name in names] == lengths and
                   [edit["parameter"] for edit in case["edits"]] == names,
                   "native corner must independently exercise width height and leaf depth")
    for edit in case["edits"]:
        curves.require(set(edit["expected_dimensions_m"]) == set(names) and type(edit["value_m"]) in (int, float) and
                       edit["value_m"] > 0.0 and edit["value_m"] != case["dimensions_m"][edit["parameter"]] and
                       edit["expected_dimensions_m"] == dict(case["dimensions_m"], **{edit["parameter"]: edit["value_m"]}),
                       "each edit must change exactly one actual live driver from the immutable original")
    intended = PureWindowsPath(case["self_path"])
    curves.require(intended.parent == PureWindowsPath(r"C:\KitSdkCandidates") and
                   intended.name == case["model_name"] + ".SLDPRT" and build["feature_count"] == 19 and build["next_id"] == 27,
                   "native corner requires its exact authored path and unextended persistent allocator")
    tree = tree_prediction(request, {"intent": {"profile": case["profile"], "feature": case["feature"], "resolved_roots": 19}})
    curves.require(tree == case["tree"], "expected tree must derive from the neutral system and feature names")
    return job, root / "Control.SLDPRT", candidate, case, tree


def dimension_state(author, dimension):
    curves.require(dimension is not None, "native rectangle is missing an owned dimension")
    full_name = str(author.get(dimension, "FullName"))
    return {"full_name": full_name, "short_name": short_name(full_name),
            "value_m": float(author.get(dimension, "SystemValue")),
            "driving": int(author.get(dimension, "DrivenState")) == 2 and not bool(author.get(dimension, "ReadOnly"))}


def snapshot(author, case):
    model = author.model
    profile = author.get(model, "FeatureByName", case["profile"])
    boss = author.get(model, "FeatureByName", case["feature"])
    curves.require(profile is not None and boss is not None, "native rectangle feature owners are missing")
    author.sketch = author.get(profile, "GetSpecificFeature2")
    manager = author.get(author.sketch, "RelationManager")
    author.get(model, "ClearSelection2", True)
    extension = author.get(model, "Extension")
    curves.require(author.get(extension, "SelectByID2", "Point1@" + case["origin"], "EXTSKETCHPOINT",
                              0.0, 0.0, 0.0, False, 0, author.sw.nothing(), 0), "actual model origin selection failed")
    selection = author.get(model, "SelectionManager")
    origin = author.typed(author.get(selection, "GetSelectedObject6", 1, -1), "SketchPoint")
    relations = []
    for relation in author.get(manager, "GetRelations", 0) or ():
        entities = list(author.get(relation, "GetEntities") or ())
        kinds = list(author.get(relation, "GetEntitiesType") or ())
        curves.require(len(entities) == len(kinds) == int(author.get(relation, "GetEntitiesCount")),
                       "native rectangle relation entity metadata is incomplete")
        relation_kind = int(author.get(relation, "GetRelationType"))
        curves.require(relation_kind in (1, 4, 5, 9), "native rectangle acquired an unsupported relation kind")
        entity_namespace = "point" if relation_kind in (1, 9) else "segment"
        bindings = [author.entity_binding(entity, entity_namespace) for entity in entities]
        curves.require(all(binding["kind"] == ("point" if relation_kind in (1, 9) else "line") for binding in bindings),
                       "native rectangle relation has an unexpected concrete entity class")
        display = author.get(relation, "GetDisplayDimension")
        dimension = None if display is None else dimension_state(author, author.get(display, "GetDimension2", 0))
        relations.append({"kind": relation_kind,
                          "suppressed": bool(author.get(relation, "Suppressed")),
                          "entity_types": kinds, "entity_ids": [list(binding["id"]) for binding in bindings],
                          "dimension": dimension, "origin_matches": [int(author.get(author.app, "IsSame", origin, entity)) == 1 for entity in entities] if relation_kind == 9 else []})
    curves.require(int(author.get(manager, "GetRelationsCount", 0)) == len(relations), "native rectangle relation enumeration is incomplete")
    author.get(model, "ClearSelection2", True)
    bodies = author.get(author.typed(model, "PartDoc"), "GetBodies2", 0, True) or ()
    return {"configuration": str(author.get(author.get(model, "GetActiveConfiguration"), "Name")),
            "tree": author.feature_tree(required_names=(case["profile"], case["feature"], case["support"])),
            "sketch_parents": [str(author.get(item, "Name")) for item in author.get(profile, "GetParents") or ()],
            "boss_parents": [str(author.get(item, "Name")) for item in author.get(boss, "GetParents") or ()],
            "geometry": author.geometry(), "relations": relations,
            "constraint_status": int(author.get(author.sketch, "GetConstrainedStatus")),
            "dimensions": {name: dimension_state(author, author.get(model, "Parameter", name)) for name in case["parameter_names"]},
            "body_count": len(bodies), "mass": author.rec.call("measure rectangle solid", author.sw.mass, model) if bodies else None,
            "whats_wrong": int(author.get(author.get(model, "Extension"), "GetWhatsWrongCount"))}


def phase(output, role, source, expected_sha, case, tree, edit, *, prior=None):
    import Swapp
    from OracleIdentity import application_identity

    work = output / role
    work.mkdir(exist_ok=False)
    recorder = curves.Recorder(work / "Record.json", {"role": role, "source": str(source), "source_sha256": expected_sha})
    result = {"role": role, "passed": False, "states": {}}
    recorder.data["result"] = result
    controller = author = None
    with Swapp.Dismisser() as dialogs:
        try:
            curves.require(curves.digest(source) == expected_sha, "native rectangle phase input changed")
            recorder.call("guard fresh rectangle oracle", Swapp.sweep)
            controller = recorder.call("start clean rectangle oracle", Swapp.Sw)
            identity = recorder.call("bind oracle executable and owned process", application_identity, controller.app)
            result["oracle_identity"] = identity
            curves.require(identity["version_matches"] and identity["sha256"] == ORACLE and controller.revision == "34.5.2",
                           "native rectangle requires exact SOLIDWORKS 2026 SP05.2")
            author = RectangleAuthor(controller.app, recorder, Swapp)
            author.model, errors, warnings = recorder.call("open exact rectangle path", controller.open, source, read_only=prior is not None)
            result.update(open_errors=errors, open_warnings=warnings)
            curves.require(author.model is not None and errors == warnings == 0 and Path(author.get(author.model, "GetPathName")).samefile(source),
                           "native rectangle load failed warned or resolved another file")
            values = edit["expected_dimensions_m"] if prior is not None else case["dimensions_m"]
            roles = prior["entity_roles"] if prior is not None else None
            signature = prior["relation_signature"] if prior is not None else None
            for label in ("Initial", "Rebuilt"):
                if label == "Rebuilt":
                    curves.require(author.get(author.model, "ForceRebuild3", False), "native rectangle rebuild failed")
                state = result["states"][label] = snapshot(author, case)
                recorder.flush()
                if roles is None:
                    roles = geometry_roles(state["geometry"], case["vertices_m"])
                observed = verify_state(author, state, case, tree, values, roles=roles, rebuilt=label == "Rebuilt")
                if signature is None:
                    signature = observed
                curves.require(observed == signature, "native rectangle relation identities changed on rebuild or reopen")
            result.update(entity_roles=roles, relation_signature=signature)
            if prior is None:
                dimension = author.get(author.model, "Parameter", edit["parameter"])
                status = int(author.get(dimension, "SetSystemValue3", edit["value_m"], 1, Swapp.nothing()))
                result["edit_status"] = status
                curves.require(status == 0 and author.get(author.model, "ForceRebuild3", False), "native rectangle driving edit or rebuild failed")
                state = result["states"]["Edited"] = snapshot(author, case)
                recorder.flush()
                observed = verify_state(author, state, case, tree, edit["expected_dimensions_m"], roles=roles, rebuilt=True)
                curves.require(observed == signature, "native rectangle driving edit changed its owned relation graph")
                derivative = work / "Edited.SLDPRT"
                curves.require(not derivative.exists(), "native rectangle edited output already exists")
                saved = recorder.call("save separate edited rectangle", controller.save_as, author.model, derivative)
                result["save_status"] = list(saved)
                curves.require(saved == (True, 0, 0) and derivative.stat().st_size > 0, "native rectangle save failed or warned")
                result.update(derivative_sha256=curves.digest(derivative), derivative_bytes=derivative.stat().st_size)
            result["passed"] = True
        except Exception as error:
            recorder.failure(error)
            result["error"] = repr(error)
        finally:
            if controller is not None:
                try:
                    if author is not None and author.model is not None:
                        controller.close_doc(author.model)
                    controller.close()
                except Exception as error:
                    recorder.failure(error, cleanup=True)
                result["controller_diagnostics"] = controller.diagnostics
    result.update(dialogs=dialogs.log, progress_windows=dialogs.progress, immutable_input=curves.digest(source) == expected_sha)
    result["passed"] = bool(result["passed"] and result["immutable_input"] and not result["dialogs"] and
                            not result.get("controller_diagnostics") and not recorder.data["cleanup_errors"])
    recorder.data.update(passed=result["passed"], numeric_check_count=len(recorder.data["checks"]))
    recorder.flush()
    return result | {"record_sha256": curves.digest(recorder.path), "numeric_check_count": len(recorder.data["checks"])}


def control_phase(output, role, seed):
    result = control(output, role, seed)
    record = json.loads((output / role / "Record.json").read_bytes())
    result["measurement"] = {key: record.get(key) for key in ("bodies", "mass", "open_errors", "open_warnings", "whats_wrong")}
    return result


def control_match(before, after):
    first, last = before["measurement"], after["measurement"]
    if not isinstance(first.get("mass"), dict) or not isinstance(last.get("mass"), dict):
        return False
    initial, final = first["mass"].get("com"), last["mass"].get("com")
    if not isinstance(initial, list) or not isinstance(final, list) or len(initial) != len(final) or len(initial) != 3:
        return False
    return (first["bodies"] == last["bodies"] == 1 and
            all(close(first["mass"].get(name), last["mass"].get(name)) for name in ("volume", "area", "mass")) and
            all(close(left, right) for left, right in zip(initial, final, strict=True)))


def run(packet, expected):
    curves.require(os.name == "nt", "native corner execution belongs to the root-owned Windows oracle")
    job, seed, candidate, case, tree = verify(packet, expected)
    exact = Path(case["self_path"])
    curves.require(not exact.exists(), "choose a fresh authored native target, existing inputs are never overwritten")
    output = packet.parent / "Inspection"
    output.mkdir(exist_ok=False)
    report = {"schema": SCHEMA, "packet_sha256": expected, "edits": [], "controls": [], "passed": False,
              "heldout_inputs_read": 0, "fcstd_conversion_accepted": False, "public_writer_qualified": False,
              "source_manifest_sha256": job["inputs_sha256"]["WriterManifest.json"],
              "source_closure_sha256": job["inputs_sha256"]["FrozenSource.json"], "oracle_sha256": ORACLE}
    phases = []

    def checkpoint():
        curves.write_json(output / "Result.json", report)

    try:
        before = control_phase(output, "ControlBefore", seed)
        report["controls"].append(before)
        phases.append(before)
        checkpoint()
        if before["passed"]:
            exact.parent.mkdir(parents=True, exist_ok=True)
            with candidate.open("rb") as source, exact.open("xb") as destination:
                copyfileobj(source, destination)
            curves.require(curves.digest(exact) == job["inputs_sha256"]["Candidate.SLDPRT"], "exact authored staging differs")
            for ordinal, edit in enumerate(case["edits"]):
                stem = ("Width", "Height", "Depth")[ordinal]
                result = phase(output, stem + "Edit", exact, job["inputs_sha256"]["Candidate.SLDPRT"], case, tree, edit)
                phases.append(result)
                entry = {"parameter": edit["parameter"], "value_m": edit["value_m"], "edit": result}
                report["edits"].append(entry)
                checkpoint()
                if result["passed"]:
                    derivative = output / (stem + "Edit") / "Edited.SLDPRT"
                    reopened = phase(output, stem + "Reopen", derivative, result["derivative_sha256"], case, tree, edit, prior=result)
                    phases.append(reopened)
                    entry["reopen"] = reopened
                entry["passed"] = bool(result["passed"] and entry.get("reopen", {}).get("passed"))
                checkpoint()
    except Exception as error:
        report["error"] = repr(error)
    finally:
        try:
            after = control_phase(output, "ControlAfter", seed)
            report["controls"].append(after)
            phases.append(after)
        except Exception as error:
            report["control_after_error"] = repr(error)
        births = [row.get("oracle_identity", {}).get("process_creation_filetime") for row in phases]
        report.update(controls_healthy=[row["passed"] for row in report["controls"]] == [True, True], expected_processes=8,
                      distinct_processes=len({value for value in births if type(value) is int and value > 0}))
        try:
            verified, _, _, _, _ = verify(packet, expected)
            report["frozen_inputs_unchanged"] = verified == job
        except Exception as error:
            report.update(frozen_inputs_unchanged=False, custody_error=repr(error))
        report["generated_unchanged"] = exact.is_file() and curves.digest(exact) == job["inputs_sha256"]["Candidate.SLDPRT"]
        report["control_measurements_match"] = len(report["controls"]) == 2 and control_match(*report["controls"])
        report["passed"] = bool(report["controls_healthy"] and report["control_measurements_match"] and report["generated_unchanged"] and
                                report["frozen_inputs_unchanged"] and "error" not in report and
                                len(phases) == report["distinct_processes"] == 8 and len(report["edits"]) == 3 and
                                all(row["passed"] for row in report["edits"]))
        report["native_acceptance_scope"] = "synthetic origin rectangle dimensions and leaf depth only, full FCStd source route remains separate"
        checkpoint()
    return report


def main():
    parser = argparse.ArgumentParser(description="Measure a generated SDK origin rectangle and three independent driving edits through ordinary COM")
    parser.add_argument("command", choices=("verify", "run"))
    parser.add_argument("packet", type=Path)
    parser.add_argument("--packet-sha256", required=True)
    args = parser.parse_args()
    packet = args.packet.resolve(strict=True)
    if args.command == "verify":
        verify(packet, args.packet_sha256)
        result = {"passed": True, "processes_started": 0}
    else:
        report = run(packet, args.packet_sha256)
        result = {key: report[key] for key in ("passed", "controls_healthy", "distinct_processes")}
    print(json.dumps(result, sort_keys=True))
    return 0 if result["passed"] else 3


if __name__ == "__main__":
    raise SystemExit(main())
