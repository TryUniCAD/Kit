def inject_probe(document, name):
    nodes = WalkDrawNodes(document)
    first = lambda kind: next(node for node in nodes if node.ClassValue.NameValue == kind)
    if name == "runtime_schema":
        document.ClassValue = RuntimeClass("uiDrawingDoc_c", 2)
    elif name == "drawing_root":
        first("moDrawing_c").ClassValue = RuntimeClass("moDrawing_c", 2)
    elif name == "populated_links":
        first("moDrawing_c").FieldsValue["n1740"] = 1
    elif name == "sheet_format":
        first("moDrSheet").FieldsValue["f3c0"] = 0
    elif name == "sheet_alias":
        first("moDrSheet").FieldsValue["f408"] = first("moDetailFolder_c")
    elif name == "material_payload":
        document.FieldsValue["has_pwmaterial"] = 1
    elif name == "trailer_marker":
        document.FieldsValue["drawing_end_marker"] = 0
    elif name == "layer_mask":
        first("moLayerMask_c").FieldsValue["f08"]["data"] = b"unqualified"
    elif name == "detail_bucket":
        first("moDetailFolder_c").FieldsValue["has_fd98"] = 1
    elif name == "sketch_rows":
        first("sgSketch").FieldsValue["points"] = ({"kind": 0},)
    elif name == "sheet_presence":
        del first("moDrSheet").FieldsValue["has_f408"]
    elif name is not None and name != "archive_version":
        raise ValueError("unknown drawing Definition qualification probe")


def main():
    job = json.load(sys.stdin)
    require(job["schema"] == "kit.sw2026.sdk-drawing-definition-process.v1", "drawing Definition job differs")
    for name in ("DocumentAssemblyValidate", "DocumentFeatureValidate", "DocumentReferenceValidate"):
        importlib.import_module("interchange.document.Validation." + name)
    tuple(codecs.lookup(name) for name in ("utf-16-le", "utf-8", "latin-1"))
    normal = registry()
    independent_rules = registry()
    AUDIT.BeginBuild()
    request = job["request"]
    canonical = construct_blank_drawing(registry=normal, request=deepcopy(request))
    independent = construct_blank_drawing(registry=independent_rules, request=deepcopy(request))
    document = generated_document(construction=independent, request=request)
    inject_probe(document, job.get("qualification_probe"))
    version = 18000 if job.get("qualification_probe") == "archive_version" else 19000
    output = WriteBlankDef(BlankGraph(document, version))
    require(output.OutputValue == canonical.streams["Contents/Definition"], "SDK complete Definition changed generated bytes")
    require(output.MapValue.CounterValue == canonical.definition_map_count, "SDK Definition native map counter differs")
    sdk_read = ReadBlankDef(output.OutputValue, 19000)
    sdk_again = WriteBlankDef(sdk_read.GraphValue)
    require(sdk_again.OutputValue == output.OutputValue
            and sdk_read.MapValue.CounterValue == output.MapValue.CounterValue
            and sdk_again.MapValue.CounterValue == output.MapValue.CounterValue,
            "SDK full Definition read and reemission differs")
    streams = dict(independent.streams)
    streams["Contents/Definition"] = output.OutputValue
    require(streams == canonical.streams, "SDK Definition changed another logical stream")
    parsed, read_archive = load_definition(output.OutputValue, normal, 19000)
    require(read_archive.left() == 0 and not parsed.tail, "complete generated Definition has unread bytes")
    require(read_archive.count == output.MapValue.CounterValue, "independent complete Definition reader map differs")
    payload = build_sldprt(streams)
    archive = SldprtArchive.from_bytes(payload)
    concept = ReadConcept(archive, 19000)
    sheet, = [node for node in ReadOwnedNodes(concept) if node.ClassValue.NameValue == "moDrSheet"]
    require(sheet.FieldsValue["f3f8"] == request["sheet"]["scale_numerator"]
            and sheet.FieldsValue["f400"] == request["sheet"]["scale_denominator"]
            and sheet.FieldsValue["f3d0"] == request["sheet"]["custom_property_view"], "public concept readback differs")
    public = open_document(payload, source_format=KDrawingFormatId, strict=False)
    require(public.drawing is not None and len(public.drawing.Sheets) == 1, "public drawing reader lost the generated sheet")
    public_refusals = refuse_research_drawing(public, linked=False)
    require(not AUDIT.DeniedReads, "complete Definition emission attempted runtime input access")
    usage = GetBodyReport(output.UsageValue)
    require(usage["completed"] and not usage["missing_schemas"], "complete Definition grammar did not finish")
    result = {"schema": "kit.sw2026.sdk-drawing-definition-result.v1", "passed": True,
              "definition_bytes": len(output.OutputValue), "definition_sha256": digest(output.OutputValue),
              "definition_map_next_index": output.MapValue.CounterValue, "all_logical_streams_identical": True,
              "artifact_bytes": len(payload), "artifact_sha256": digest(payload),
              "artifact_base64": b64encode(payload).decode("ascii"), "usage": usage,
              "complete_research_readback": True, "public_reader_passed": True,
              "complete_sdk_readback": True, "sdk_read_write_identical": True,
              "sheet_name": request["sheet"]["name"],
              "sheet_scale": [sheet.FieldsValue["f3f8"], sheet.FieldsValue["f400"]],
              "property_view": sheet.FieldsValue["f3d0"],
              "runtime_input_file_access_attempts": len(AUDIT.DeniedReads),
              "heldout_inputs_read": 0, "vendor_runtime_executed": False,
              "native_acceptance": False, "public_write_refusals": public_refusals}
    print(json.dumps(result, sort_keys=True, allow_nan=False))


if __name__ == "__main__":
    main()
