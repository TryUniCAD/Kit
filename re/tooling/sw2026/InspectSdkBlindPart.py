from __future__ import annotations

import argparse
import json
import os
from pathlib import Path, PureWindowsPath
from shutil import copyfileobj

import AuthorCurves as curves
from AuthorRectangleAnchors import CONTROL, ORACLE, control


SCHEMA = "kit.sw2026.sdk-blind-part-native-comparison.v1"
TOOLS = (
    "AuthorCurves.py", "AuthorRectangleAnchors.py", "InspectFresh.py",
    "InspectSdkBlindPart.py", "OracleIdentity.py", "Swapp.py",
)


def checked(root, name, expected):
    path = (root / name).resolve(strict=True)
    curves.require(path.parent == root and path.is_file() and curves.digest(path) == expected,
                   f"frozen part evidence differs: {name}")
    return path


def verify(packet, expected):
    root = packet.parent.resolve(strict=True)
    job = json.loads(checked(root, packet.name, expected).read_bytes())
    curves.require(job["schema"] == SCHEMA and job["oracle_sha256"] == ORACLE
                   and job["heldout_inputs_read"] == 0, "expected a pinned disclosed part trial")
    tools = (root / "Tools").resolve(strict=True)
    curves.require(Path(__file__).resolve().parent == tools and set(job["tools_sha256"]) == set(TOOLS),
                   "the trial is missing its frozen observer")
    for name, digest in job["tools_sha256"].items():
        checked(tools, name, digest)
    seed = checked(root, "Control.SLDPRT", CONTROL)
    candidate = checked(root, "Candidate.SLDPRT", job["generated_sha256"])
    case = json.loads(checked(root, "Case.json", job["case_sha256"]).read_bytes())
    proof = json.loads(checked(root, "BuildProof.json", job["build_proof_sha256"]).read_bytes())
    row = next(value for value in proof["rows"] if value["design"] == job["design"])
    checked(root, "NeutralRequest.json", row["request_sha256"])
    requested = PureWindowsPath(case["intent"]["self_path"])
    curves.require(proof["passed"] and proof["guarded_runtime_reads"] == 0
                   and row["build_sha256"] == row["build_repeat_sha256"]
                   and row["file_sha256"] == job["generated_sha256"] and row["file_bytes"] == candidate.stat().st_size
                   and len(row["streams"]) == 10 and requested.parent == PureWindowsPath(r"C:\KitSdkCandidates")
                   and requested.name == case["intent"]["model_name"] + ".SLDPRT",
                   "generated bytes do not bind two clean ten-stream builds and the encoded path")
    curves.require(len(job["expected_top_level"]) == case["intent"]["resolved_roots"],
                   "native top-level prediction has incomplete feature coverage")
    return job, case, seed, candidate


def snapshot(author, case):
    intent = case["intent"]
    model = author.model
    sketch = author.get(model, "FeatureByName", intent["profile"])
    boss = author.get(model, "FeatureByName", intent["feature"])
    author.sketch = author.get(sketch, "GetSpecificFeature2")
    parameter = author.get(model, "Parameter", case["edit"]["dimension"])
    configuration = author.get(model, "GetActiveConfiguration")
    manager = author.get(author.sketch, "RelationManager")
    sketch_dimensions = author.get(sketch, "GetFirstDisplayDimension")
    count = len(author.get(author.typed(model, "PartDoc"), "GetBodies2", 0, True) or ())
    return {
        "configuration": str(author.get(configuration, "Name")),
        "tree": author.feature_tree(required_names=(intent["profile"], intent["feature"], intent["support"])),
        "sketch_parents": [str(author.get(item, "Name")) for item in author.get(sketch, "GetParents") or ()],
        "boss_parents": [str(author.get(item, "Name")) for item in author.get(boss, "GetParents") or ()],
        "sketch_geometry": author.geometry(),
        "sketch_relation_count": int(author.get(manager, "GetRelationsCount", 0)),
        "sketch_has_display_dimensions": sketch_dimensions is not None,
        "dimension_m": float(author.get(parameter, "SystemValue")),
        "dimension_driving": int(author.get(parameter, "DrivenState")) == 2 and not author.get(parameter, "ReadOnly"),
        "whats_wrong": int(author.get(author.get(model, "Extension"), "GetWhatsWrongCount")),
        "body_count": count,
        "mass": author.rec.call("measure generated part mass", author.sw.mass, model) if count else None,
    }


def verify_state(recorder, state, case, expected_top_level, *, edited):
    intent = case["intent"]
    target = case["edit"]["expected"] if edited else case["expected_initial"]
    expected_depth = case["edit"]["new_depth_m"] if edited else intent["depth_m"]
    observed_top = [[row["name"], row["type"]] for row in state["tree"] if row["parent"] is None]
    curves.require(observed_top == expected_top_level and not any(row["suppressed"] for row in state["tree"]),
                   "ordered native part feature tree differs")
    curves.require(state["configuration"] == intent["configuration_name"] and
                   state["sketch_parents"] == [intent["support"]] and state["boss_parents"] == [intent["profile"]],
                   "native part configuration or sketch-to-boss dependency differs")
    curves.require(not state["sketch_has_display_dimensions"] and state["dimension_driving"]
                   and state["sketch_relation_count"] == intent["fixed_relations_in_user_sketch"],
                   "editable depth or unconstrained sketch intent differs")
    curves.require(state["whats_wrong"] == 0 and state["body_count"] == target["body_count"],
                   "native part has diagnostics or lacks its analytic solid")
    recorder.close_number("live blind depth", state["dimension_m"], expected_depth)
    for key, intended in (("volume", "volume_m3"), ("area", "area_m2")):
        recorder.close_number(key, state["mass"][key], target[intended], absolute=1e-16)
    for actual, expected in zip(state["mass"]["com"], target["centre_of_mass_m"], strict=True):
        recorder.close_number("part centre of mass", actual, expected)
    vertices = intent["vertices_m"]
    edges = sorted(tuple(sorted((tuple(first), tuple(last)))) for first, last in zip(vertices, vertices[1:] + vertices[:1], strict=True))
    geometry = state["sketch_geometry"]
    curves.require(len(geometry) == intent["sketch_lines"]
                   and all(row["kind"] == "line" and not row["construction"] for row in geometry),
                   "native sketch is not the requested ordinary polygon")
    observed_edges = sorted(tuple(sorted((tuple(row["start"]), tuple(row["end"])))) for row in geometry)
    for observed, expected in zip(observed_edges, edges, strict=True):
        for actual, target_point in zip(observed, expected, strict=True):
            for coordinate, expected_coordinate in zip(actual, target_point, strict=True):
                recorder.close_number("native rectangle endpoint", coordinate, expected_coordinate)


def phase(root, role, source, digest, job, case, *, edited_tree=None):
    import Swapp
    from OracleIdentity import application_identity

    output = root / role
    output.mkdir()
    rec = curves.Recorder(output / "Record.json", {"role": role, "source": str(source), "source_sha256": digest})
    result = {"passed": False, "role": role, "states": {}}
    rec.data["result"] = result
    controller = author = None
    with Swapp.Dismisser() as dialogs:
        try:
            curves.require(curves.digest(source) == digest, "native part bytes differ before opening")
            rec.call("guard fresh part oracle", Swapp.sweep)
            controller = rec.call("start clean part oracle", Swapp.Sw)
            identity = rec.call("bind executable and process", application_identity, controller.app)
            result["oracle_identity"] = identity
            curves.require(identity["version_matches"] and identity["sha256"] == ORACLE and controller.revision == "34.5.2",
                           "wrong SOLIDWORKS build for the part lifecycle")
            author = curves.CurveAuthor(controller.app, rec, Swapp)
            reopening = edited_tree is not None
            author.model, errors, warnings = rec.call("open the exact part path", controller.open, source, read_only=reopening)
            result.update(open_errors=errors, open_warnings=warnings)
            curves.require(author.model is not None and errors == warnings == 0
                           and Path(author.get(author.model, "GetPathName")).samefile(source),
                           "native part load failed, warned, or resolved a different file")
            for label in ("Initial", "Rebuilt"):
                if label == "Rebuilt":
                    curves.require(author.get(author.model, "ForceRebuild3", False), "part rebuild failed")
                result["states"][label] = snapshot(author, case)
                rec.flush()
            for label, value in result["states"].items():
                verify_state(rec, value, case, job["expected_top_level"], edited=reopening)
            tree = result["states"]["Initial"]["tree"]
            curves.require(tree == result["states"]["Rebuilt"]["tree"] and (not reopening or tree == edited_tree),
                           "the complete native feature tree changed")
            if not reopening:
                parameter = author.get(author.model, "Parameter", case["edit"]["dimension"])
                status = int(author.get(parameter, "SetSystemValue3", case["edit"]["new_depth_m"], 1, Swapp.nothing()))
                result["edit_status"] = status
                curves.require(status == 0 and author.get(author.model, "ForceRebuild3", False), "native part depth edit or rebuild failed")
                value = snapshot(author, case)
                result["states"]["Edited"] = value
                rec.flush()
                verify_state(rec, value, case, job["expected_top_level"], edited=True)
                curves.require(value["tree"] == tree, "driving edit changed the complete native tree")
                derivative = output / "Edited.SLDPRT"
                curves.require(not derivative.exists(), "part derivative already exists")
                saved = rec.call("save a new edited native part", controller.save_as, author.model, derivative)
                result["save_status"] = list(saved)
                curves.require(saved == (True, 0, 0) and derivative.stat().st_size > 0, "part save failed or warned")
                result.update(derivative_sha256=curves.digest(derivative), derivative_bytes=derivative.stat().st_size)
            result["passed"] = True
        except Exception as error:
            rec.failure(error)
            result["error"] = repr(error)
        finally:
            if controller is not None:
                try:
                    if author is not None and author.model is not None:
                        controller.close_doc(author.model)
                    controller.close()
                except Exception as error:
                    rec.failure(error, cleanup=True)
                result["controller_diagnostics"] = controller.diagnostics
    result.update(dialogs=dialogs.log, progress_windows=dialogs.progress, immutable_bytes=curves.digest(source) == digest)
    result["passed"] = bool(result["passed"] and result["immutable_bytes"] and not result["dialogs"]
                            and not result.get("controller_diagnostics") and not rec.data["cleanup_errors"])
    rec.data.update(passed=result["passed"], numeric_check_count=len(rec.data["checks"]))
    rec.flush()
    return result | {"record_sha256": curves.digest(rec.path), "numeric_check_count": len(rec.data["checks"])}


def run(packet, packet_hash):
    curves.require(os.name == "nt", "native part lifecycle must use the Windows guest")
    job, case, seed, candidate = verify(packet, packet_hash)
    output = packet.parent / "Inspection"
    output.mkdir()
    phases = {}
    report = {"schema": SCHEMA, "packet_sha256": packet_hash, "phases": phases, "passed": False, "heldout_inputs_read": 0}
    generated = Path(case["intent"]["self_path"])

    def checkpoint():
        curves.write_json(output / "Result.json", report)

    try:
        phases["ControlBefore"] = control(output, "ControlBefore", seed)
        checkpoint()
        if phases["ControlBefore"]["passed"]:
            generated.parent.mkdir(exist_ok=True)
            with candidate.open("rb") as source, generated.open("xb") as destination:
                copyfileobj(source, destination)
            phases["Generated"] = phase(output, "Generated", generated, job["generated_sha256"], job, case)
            checkpoint()
            trial = phases["Generated"]
            if trial["passed"]:
                phases["FreshReopen"] = phase(output, "FreshReopen", output / "Generated" / "Edited.SLDPRT",
                                              trial["derivative_sha256"], job, case,
                                              edited_tree=trial["states"]["Edited"]["tree"])
    except Exception as error:
        report["error"] = repr(error)
    finally:
        phases["ControlAfter"] = control(output, "ControlAfter", seed)
        verified, _, _, _ = verify(packet, packet_hash)
        births = {value.get("oracle_identity", {}).get("process_creation_filetime") for value in phases.values() if value.get("oracle_identity")}
        report.update(controls_healthy=phases["ControlBefore"]["passed"] and phases["ControlAfter"]["passed"],
                      generated_unchanged=generated.is_file() and curves.digest(generated) == job["generated_sha256"],
                      frozen_inputs_unchanged=verified == job, distinct_processes=len(births - {None}))
        report["passed"] = (report["generated_unchanged"] and report["frozen_inputs_unchanged"]
                            and len(phases) == report["distinct_processes"] == 4 and all(value["passed"] for value in phases.values()))
        checkpoint()
    return report


def main():
    parser = argparse.ArgumentParser(description="Measure the first complete SDK blind rectangle in ordinary SOLIDWORKS COM")
    parser.add_argument("command", choices=("verify", "run"))
    parser.add_argument("packet", type=Path)
    parser.add_argument("--packet-sha256", required=True)
    args = parser.parse_args()
    packet = args.packet.resolve(strict=True)
    if args.command == "verify":
        verify(packet, args.packet_sha256)
        result = {"passed": True, "processes_started": 0}
    else:
        report = run(packet, args.packet_sha256)
        result = {name: report[name] for name in ("passed", "controls_healthy", "distinct_processes")}
    print(json.dumps(result, sort_keys=True))
    return 0 if result["passed"] else 3


if __name__ == "__main__":
    raise SystemExit(main())
