def digest(path):
    return sha256(path.read_bytes()).hexdigest()


def encoded(value):
    return (json.dumps(value, sort_keys=True, indent=2, allow_nan=False) + "\n").encode()


def save(path, value):
    with path.open("xb") as output:
        output.write(encoded(value))
    return digest(path)


def verify_source(base, expected):
    manifest_path = base / "FrozenSource.json"
    require(digest(manifest_path) == expected, "SDK source manifest identity differs")
    manifest = json.loads(manifest_path.read_bytes())
    require(manifest["file_count"] == len(manifest["files_sha256"]), "SDK source count differs")
    root = base / "Kit"
    for relative, identity in manifest["files_sha256"].items():
        path = root / relative
        require(not path.is_symlink() and path.resolve().is_relative_to(root.resolve()) and digest(path) == identity,
                "SDK source custody differs: " + relative)
    return {"manifest_sha256": expected, "file_count": manifest["file_count"], "source_revision": manifest["base"]}


def execute(root, script, mode, request):
    arguments = ((sys.executable, "-I", "-B", str(root / "re/tooling/sw2026" / script), str(root), mode)
                 if script == "SdkCircleProof.py" else
                 (sys.executable, "-I", "-B", str(root / "re/tooling/sw2026" / script), mode, str(root)))
    result = subprocess.run(arguments, input=encoded(request), capture_output=True, check=False, timeout=120)
    require(result.returncode == 0, script + " failed: " + result.stderr.decode(errors="replace") + result.stdout.decode(errors="replace"))
    report = json.loads(result.stdout)
    require(report["passed"] is True, "SDK process did not pass")
    if script == "SdkCircleProof.py":
        require(report["runtime_input_file_reads"] == report["sdk_runtime_research_imports"] == 0,
                "guarded writer consulted another input or research implementation")
    return report


def qualification_cases():
    cases = (
        ("IndependentTranslatedDiameter", "front", [-9.843, 3.617], 6.375, 11.625, "diameter", "blind", False, None),
        ("IndependentReverseTopRadius", "top", [5.219, -8.413], 9.875, 14.375, "radial", "blind", True, None),
        ("IndependentMidRightDiameter", "right", [-4.613, 7.319], 12.125, 17.875, "diameter", "mid_plane", False, None),
        ("IndependentTwoReverseTop", "top", [2.719, 5.137], 4.625, 9.375, "diameter", "two_directions", True, 13.125),
    )
    for name, plane, center, radius, depth, mode, condition, reverse, second in cases:
        case = {"name": name, "split": "discovery", "plane": plane,
                "profile": {"kind": "circle", "center_mm": center, "radius_mm": radius},
                "depth_mm": depth, "reverse": reverse, "dimension_kind": mode,
                "end_condition": condition, "expected_bodies": 1, "edit": {"target": "curve-0", "factor": 1.137}}
        if second is not None:
            case["reverse_depth_mm"] = second
        yield case


def qualify(writer, reader, directory):
    rows = []
    for case in qualification_cases():
        spec = project_spec(case)
        request = neutral_request(writer / "Kit", spec, 1794974400)
        output = directory / spec["name"]
        output.mkdir()
        save(output / "SourceSpec.json", case)
        request_hash = save(output / "Request.json", request)
        first = execute(writer / "Kit", "SdkCircleProof.py", "build", request)
        repeated = execute(writer / "Kit", "SdkCircleProof.py", "build", request)
        require(first == repeated, "two independent generated builds differ")
        prepared = execute(writer / "Kit", "SdkCircleProof.py", "prepare", {**request, "build": first})
        require(prepared["exact_repacked_archive"] is True and len(prepared["streams"]) == 10,
                "complete typed container qualification failed")
        payload = b64decode(first["blob"], validate=True)
        require(sha256(payload).hexdigest() == first["sha256"], "generated bytes differ")
        candidate = output / (spec["name"] + ".SLDPRT")
        with candidate.open("xb") as stream:
            stream.write(payload)
        expected = analytic(spec)
        authored = first["dimensions"]
        require(abs(authored["volume_m3"] - expected["volume_m3"]) <= 1e-18 and
                abs(authored["area_m2"] - expected["area_m2"]) <= 1e-15 and
                all(abs(a - b) <= 1e-12 for a, b in zip(authored["com_m"], expected["com_m"], strict=True)),
                "independent analytic predictor disagrees")
        read_request = {"path": str(candidate), "sha256": first["sha256"], "case": spec["name"], "phase": "independent-host-qualification",
                        "axis": {"front": "z", "right": "x", "top": "y"}[spec["plane"]], "feature": spec["feature_name"],
                        "mode": spec["mode"], "center_mm": list(spec["center_mm"]), "radius_mm": spec["radius_mm"],
                        "depth_mm": spec["depth_mm"], "second_mm": spec["second_mm"], "reverse": spec["reverse"],
                        "end_condition": spec["end_condition"]}
        read = execute(reader / "Kit", "CheckSdkCircleRead.py", "worker", read_request)
        require(digest(candidate) == first["sha256"], "reader altered generated candidate")
        for value in (first, repeated):
            value.pop("blob")
        rows.append({"name": spec["name"], "request_sha256": request_hash, "candidate_sha256": first["sha256"],
                     "build_sha256": save(output / "Build.json", first), "repeat_sha256": save(output / "Repeat.json", repeated),
                     "prepare_sha256": save(output / "Prepare.json", prepared), "read_sha256": save(output / "Read.json", read),
                     "analytic": expected, "passed": True, "guarded_runtime_input_reads": 0,
                     "sdk_research_imports": 0, "complete_logical_streams": 10, "fresh_processes": 4})
        print(json.dumps(rows[-1], sort_keys=True), flush=True)
    return rows


