def require(value, message):
    if not value:
        raise ValueError(message)


def name_document(document, names):
    require(type(document) is CadDocument and len(names) == 3, "expected an actual typed part and three authored labels")
    sketch, = document.sketches
    boss, = document.feature_timeline
    identities = (*sketch.parameter_ids, *boss.parameter_ids)
    names_by_id = dict(zip(identities, names, strict=True))
    parameters = tuple(replace(item, name=names_by_id[item.id]) for item in document.parameters)
    owners = {sketch.id: sketch.name, boss.id: boss.name}
    expected = {(owners[item.owner_id], item.name): item.value.value for item in parameters}
    require(len(expected) == 3, "the independent request must model three distinct driver owners")
    return replace(document, parameters=parameters), expected


def verify_names(candidate, expected):
    words = candidate.StreamsValue["swXmlContents/KeyWords"]
    configs, features = ParseKeywords(words)
    keywords = [(feature.name, dimension.name, dimension.value_mm)
                for feature in features for dimension in feature.dimensions]
    value = open_document(candidate.BytesValue, source_format="solidworks.sldprt", strict=True,
                          include_brep=False, include_tessellation=False)
    owners = {item.id: item.name for item in value.feature_timeline}
    drivers = [(owners.get(item.owner_id), item.name, item.value.value)
               for item in value.parameters if item.role.value == "driving" and item.value.unit == "mm"]
    for label, rows in (("KeyWords", keywords), ("typed public driver", drivers)):
        require(len(rows) == 3 and {(owner, name) for owner, name, _ in rows} == expected.keys(),
                label + " did not preserve the three actual names and owners")
        require(all(isclose(value, expected[owner, name], rel_tol=1e-12) for owner, name, value in rows),
                label + " driver length differs from its independent neutral input")
    require(value.metadata["solidworks.typed_resolved_semantics"]["status"] == "supplemented",
            "named drivers must use the typed public source graph")
    return {"keyword_dimensions": keywords, "typed_dimensions": drivers}


def main():
    request = json.load(sys.stdin)
    inputs = settings(request["settings"])
    presentation = input_value(request["rectangle_dimensions"], inputs)
    document = FromData(request["document"])
    named, expected = name_document(document, request["driver_names"])
    tuple(lookup(name) for name in ("utf-16-le", "utf-8", "latin-1"))
    AUDIT.BeginBuild()
    original = MakeRectDimPart(document, inputs, presentation)
    generated = MakeRectDimPart(named, inputs, presentation)
    repeated = MakeRectDimPart(named, inputs, presentation)
    require(generated.BytesValue == repeated.BytesValue, "same named input changed its generated bytes")
    changed = sorted(name for name, item in generated.StreamsValue.items() if item != original.StreamsValue[name])
    require(changed == ["Contents/Config-0-ResolvedFeatures", "swXmlContents/KeyWords"],
            "renaming drivers changed an unrelated native stream")
    require(all(len(generated.StreamsValue[name]) > len(original.StreamsValue[name]) for name in changed),
            "longer authored driver labels did not extend their actual streams")
    runtime_reads = len(AUDIT.DeniedReads)
    require(not runtime_reads, "named generation attempted runtime file or process access")
    AUDIT.Importing = True
    result = verify_names(generated, expected)
    print(json.dumps(result | {"passed": True, "runtime_input_reads": runtime_reads,
                               "legacy_sha256": sha256(original.BytesValue).hexdigest(),
                               "generated_sha256": sha256(generated.BytesValue).hexdigest(),
                               "changed_streams": changed, "zero_native_processes": True},
                     ensure_ascii=False, sort_keys=True))


if __name__ == "__main__":
    main()
