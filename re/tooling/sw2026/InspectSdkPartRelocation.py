from pathlib import Path, PureWindowsPath
from shutil import copyfileobj
import json
import os
import sys

from InspectSdkBlindPart import phase, verify
from AuthorCurves import digest, require, write_json
from AuthorRectangleAnchors import control


def run(path, packet_sha):
    require(os.name == "nt", "relocation requires the pinned Windows guest")
    job, case, seed, original, tree = verify(path, packet_sha)
    output = path.parent / "Inspection"
    output.mkdir()
    report = {"schema": "kit.sw2026.sdk-part-relocation-discovery.v1", "prior_packet_sha256": packet_sha,
              "generated_sha256": job["generated_sha256"], "observer_sha256": digest(Path(__file__)),
              "phases": {}, "passed": False, "heldout_inputs_read": 0}

    def checkpoint():
        write_json(output / "Result.json", report)

    rel = output / "IndependentLibrary"
    rel.mkdir()
    self_path = PureWindowsPath(case["intent"]["self_path"])
    relocated = rel / self_path.name
    require(not Path(self_path).exists(), "the encoded path for the independent part must not exist")
    report["encoded_self_path_present_before"] = False
    require(PureWindowsPath(relocated).drive.casefold() != self_path.drive.casefold(),
            "the relocation must open outside the archived drive")
    with original.open("rb") as source, relocated.open("xb") as destination:
        copyfileobj(source, destination)
    require(digest(relocated) == report["generated_sha256"], "relocation changed the generated bytes")
    report.update(relocation_drive_changed=True, relocated_input_bytes=relocated.stat().st_size)
    phases = report["phases"]
    try:
        phases["ControlBefore"] = control(output, "ControlBefore", seed)
        checkpoint()
        if phases["ControlBefore"]["passed"]:
            phases["Relocated"] = phase(output, "Relocated", relocated, report["generated_sha256"], case, tree)
            checkpoint()
            trial = phases["Relocated"]
            if trial["passed"]:
                phases["FreshReopen"] = phase(output, "FreshReopen", output / "Relocated" / "Edited.SLDPRT",
                                              trial["derivative_sha256"], case, tree,
                                              edited_tree=trial["states"]["Edited"]["tree"])
    finally:
        phases["ControlAfter"] = control(output, "ControlAfter", seed)
        report["controls_healthy"] = phases["ControlBefore"]["passed"] and phases["ControlAfter"]["passed"]
        report["relocated_input_immutable"] = digest(relocated) == digest(original)
        report["encoded_self_path_present_after"] = Path(self_path).exists()
        require(not report["encoded_self_path_present_after"], "the relocation populated the encoded self path")
        stamps = {item["oracle_identity"]["process_creation_filetime"] for item in phases.values() if item.get("oracle_identity")}
        report["distinct_processes"] = len(stamps)
        report["passed"] = (report["relocated_input_immutable"] and len(phases) == len(stamps) == 4
                            and all(item["passed"] for item in phases.values()))
        checkpoint()
    return report["passed"]


if __name__ == "__main__":
    assert len(sys.argv) == 3
    raise SystemExit(0 if run(Path(sys.argv[1]).resolve(strict=True), sys.argv[2]) else 3)
